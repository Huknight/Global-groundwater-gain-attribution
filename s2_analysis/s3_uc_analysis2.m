%% ===================== Construct monthly-oracle valid mask =====================

% A pixel is retained only when:
%   1. It belongs to CommonValid.
%   2. The observed dGWS is finite for all 36 months.
%   3. All nine model predictions are finite for all 36 months.

oracleValidMask = ...
    CommonValid & ...
    all(isfinite(observedTest), 3);

for iModel = 1:nModel

    thisPrediction = ...
        predictionStack(:, :, :, iModel);

    oracleValidMask = ...
        oracleValidMask & ...
        all(isfinite(thisPrediction), 3);
end

nOracleValidPixel = nnz(oracleValidMask);

validPixelMonthMask = repmat( ...
    oracleValidMask, ...
    [1, 1, nTestMonth]);

nValidPixelMonth = nnz(validPixelMonthMask);

fprintf('\nMonthly-oracle valid pixels      : %d\n', ...
    nOracleValidPixel);

fprintf('Monthly-oracle valid pixel-months: %d\n', ...
    nValidPixelMonth);

%% ===================== Calculate monthly absolute errors =====================

observedTest4D = reshape( ...
    observedTest, ...
    nLat, ...
    nLon, ...
    nTestMonth, ...
    1);

absoluteErrorStack = abs( ...
    predictionStack - ...
    observedTest4D);

% Invalid pixels are set to Inf during ranking.
invalidPixelMonthModelMask = repmat( ...
    ~oracleValidMask, ...
    [1, 1, nTestMonth, nModel]);

absoluteErrorStack(invalidPixelMonthModelMask) = Inf;

clear observedTest4D invalidPixelMonthModelMask

%% ===================== Monthly exact best and second-best models =====================

[sortedModelErrors, sortedModelIndices] = sort( ...
    absoluteErrorStack, ...
    4, ...
    'ascend');

monthlyBestModelIdx = ...
    double(sortedModelIndices(:, :, :, 1));

monthlySecondBestModelIdx = ...
    double(sortedModelIndices(:, :, :, 2));

monthlyBestAbsoluteError = ...
    sortedModelErrors(:, :, :, 1);

monthlySecondBestAbsoluteError = ...
    sortedModelErrors(:, :, :, 2);

monthlyBestModelIdx(~validPixelMonthMask) = NaN;
monthlySecondBestModelIdx(~validPixelMonthMask) = NaN;

monthlyBestAbsoluteError(~validPixelMonthMask) = NaN;
monthlySecondBestAbsoluteError(~validPixelMonthMask) = NaN;

clear sortedModelErrors sortedModelIndices

%% ===================== Construct monthly oracle prediction sequence =====================

monthlyOraclePrediction = nan( ...
    nLat, ...
    nLon, ...
    nTestMonth);

for iModel = 1:nModel

    thisPrediction = ...
        predictionStack(:, :, :, iModel);

    thisWinnerMask = ...
        validPixelMonthMask & ...
        monthlyBestModelIdx == iModel;

    monthlyOraclePrediction(thisWinnerMask) = ...
        thisPrediction(thisWinnerMask);
end

monthlyOraclePrediction(~validPixelMonthMask) = NaN;

%% ===================== Monthly group-level rankings =====================

% Linear local indices:
%   1 = AR
%   2 = ARIMA
%   3 = SARIMA
%
% Nonlinear local indices:
%   1 = SVM
%   2 = RF
%   3 = LSTM
%
% Hydroclimatic-X local indices:
%   1 = SVMX
%   2 = RFX
%   3 = LSTMX

[linearBestError, bestLinearLocalIdx] = min( ...
    absoluteErrorStack(:, :, :, 1:3), ...
    [], ...
    4);

[nonlinearBestError, bestNonlinearLocalIdx] = min( ...
    absoluteErrorStack(:, :, :, 4:6), ...
    [], ...
    4);

[nonlinearXBestError, bestNonlinearXLocalIdx] = min( ...
    absoluteErrorStack(:, :, :, 7:9), ...
    [], ...
    4);

groupBestErrorStack = cat( ...
    4, ...
    linearBestError, ...
    nonlinearBestError, ...
    nonlinearXBestError);

[sortedGroupErrors, sortedGroupIndices] = sort( ...
    groupBestErrorStack, ...
    4, ...
    'ascend');

monthlyBestGroupIdx = ...
    double(sortedGroupIndices(:, :, :, 1));

monthlySecondBestGroupIdx = ...
    double(sortedGroupIndices(:, :, :, 2));

monthlyBestGroupError = ...
    sortedGroupErrors(:, :, :, 1);

monthlySecondBestGroupError = ...
    sortedGroupErrors(:, :, :, 2);

monthlyBestGroupIdx(~validPixelMonthMask) = NaN;
monthlySecondBestGroupIdx(~validPixelMonthMask) = NaN;

bestLinearLocalIdx(~validPixelMonthMask) = NaN;
bestNonlinearLocalIdx(~validPixelMonthMask) = NaN;
bestNonlinearXLocalIdx(~validPixelMonthMask) = NaN;

monthlyBestGroupError(~validPixelMonthMask) = NaN;
monthlySecondBestGroupError(~validPixelMonthMask) = NaN;

clear sortedGroupErrors sortedGroupIndices groupBestErrorStack
clear linearBestError nonlinearBestError nonlinearXBestError

%% ===================== Verify model-level and group-level winners =====================

reconstructedBestModelIdx = nan( ...
    nLat, ...
    nLon, ...
    nTestMonth);

maskBestLinearGroup = ...
    validPixelMonthMask & ...
    monthlyBestGroupIdx == 1;

maskBestNonlinearGroup = ...
    validPixelMonthMask & ...
    monthlyBestGroupIdx == 2;

maskBestNonlinearXGroup = ...
    validPixelMonthMask & ...
    monthlyBestGroupIdx == 3;

reconstructedBestModelIdx(maskBestLinearGroup) = ...
    bestLinearLocalIdx(maskBestLinearGroup);

reconstructedBestModelIdx(maskBestNonlinearGroup) = ...
    bestNonlinearLocalIdx(maskBestNonlinearGroup) + 3;

reconstructedBestModelIdx(maskBestNonlinearXGroup) = ...
    bestNonlinearXLocalIdx(maskBestNonlinearXGroup) + 6;

winnerMismatchCount = nnz( ...
    validPixelMonthMask & ...
    reconstructedBestModelIdx ~= monthlyBestModelIdx);

if winnerMismatchCount > 0

    warning([ ...
        'The model-level and group-level monthly winners differ at ', ...
        '%d pixel-months. Check tie handling.'], ...
        winnerMismatchCount);
end

%% ===================== Monthly gain-category classification =====================

monthlyGainClassIdx = nan( ...
    nLat, ...
    nLon, ...
    nTestMonth);

% Class 1: No gain
% Linear group wins, and AR is the best linear model.
maskNoGain = ...
    validPixelMonthMask & ...
    monthlyBestGroupIdx == 1 & ...
    bestLinearLocalIdx == 1;

% Class 2: Linear gain
% Linear group wins, and ARIMA or SARIMA is best.
maskLinearGain = ...
    validPixelMonthMask & ...
    monthlyBestGroupIdx == 1 & ...
    (bestLinearLocalIdx == 2 | ...
     bestLinearLocalIdx == 3);

% Class 3: Nonlinear gain
maskNonlinearGain = ...
    validPixelMonthMask & ...
    monthlyBestGroupIdx == 2;

% Class 4: Clean hydroclimatic gain
% The X group wins, the nonlinear group is second, and the best X model
% is paired with the corresponding best nonlinear model.
maskHydroclimaticGain = ...
    validPixelMonthMask & ...
    monthlyBestGroupIdx == 3 & ...
    monthlySecondBestGroupIdx == 2 & ...
    bestNonlinearXLocalIdx == ...
    bestNonlinearLocalIdx;

% Class 5: Mixed gain
maskMixedGain = ...
    validPixelMonthMask & ...
    monthlyBestGroupIdx == 3 & ...
    ~maskHydroclimaticGain;

monthlyGainClassIdx(maskNoGain) = 1;
monthlyGainClassIdx(maskLinearGain) = 2;
monthlyGainClassIdx(maskNonlinearGain) = 3;
monthlyGainClassIdx(maskHydroclimaticGain) = 4;
monthlyGainClassIdx(maskMixedGain) = 5;

%% ===================== Gain-category diagnostics =====================

monthlyClassSum = ...
    double(maskNoGain) + ...
    double(maskLinearGain) + ...
    double(maskNonlinearGain) + ...
    double(maskHydroclimaticGain) + ...
    double(maskMixedGain);

nAssignedPixelMonth = nnz( ...
    validPixelMonthMask & ...
    monthlyClassSum == 1);

nUnassignedPixelMonth = nnz( ...
    validPixelMonthMask & ...
    monthlyClassSum == 0);

nMultiAssignedPixelMonth = nnz( ...
    validPixelMonthMask & ...
    monthlyClassSum > 1);

if nUnassignedPixelMonth > 0 || ...
        nMultiAssignedPixelMonth > 0

    warning([ ...
        'Monthly attribution contains %d unassigned and %d ', ...
        'multi-assigned pixel-months.'], ...
        nUnassignedPixelMonth, ...
        nMultiAssignedPixelMonth);
end

%% ===================== Calculate annual monthly-oracle metrics =====================

monthlyFusionNRMSEAnnual = nan( ...
    nLat, ...
    nLon, ...
    nYear);

monthlyFusionTDAAnnual = nan( ...
    nLat, ...
    nLon, ...
    nYear);

for iYear = 1:nYear

    monthStart = ...
        (iYear - 1) .* 12 + 1;

    monthEnd = ...
        iYear .* 12;

    thisObserved = ...
        observedTest(:, :, monthStart:monthEnd);

    thisPrediction = ...
        monthlyOraclePrediction(:, :, monthStart:monthEnd);

    monthlyFusionNRMSEAnnual(:, :, iYear) = ...
        calculateNRMSEMap( ...
        thisObserved, ...
        thisPrediction, ...
        oracleValidMask);

    monthlyFusionTDAAnnual(:, :, iYear) = ...
        calculateTDAMap( ...
        thisObserved, ...
        thisPrediction, ...
        oracleValidMask);
end

% Primary manuscript-consistent metrics:
% mean of the 2022, 2023, and 2024 annual values.

monthlyFusionNRMSEMean = mean( ...
    monthlyFusionNRMSEAnnual, ...
    3, ...
    'omitnan');

monthlyFusionTDAMean = mean( ...
    monthlyFusionTDAAnnual, ...
    3, ...
    'omitnan');

monthlyFusionNRMSEMean(~oracleValidMask) = NaN;
monthlyFusionTDAMean(~oracleValidMask) = NaN;

%% ===================== Combined 36-month metrics =====================

monthlyFusionNRMSE36 = calculateNRMSEMap( ...
