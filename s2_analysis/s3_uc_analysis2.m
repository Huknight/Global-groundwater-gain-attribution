%% s3_uc_analysis2.m
% Purpose:
%   Construct an ex-post monthly oracle fusion using nine candidate models
%   for the 2022-2024 groundwater forecasting period.
%
% Monthly oracle selection:
%   At each pixel and month, select the model prediction with the minimum
%   absolute error relative to the observed dGWS value.
%
% Important:
%   The monthly winner is selected using realized test-period observations.
%   Therefore, this analysis represents a retrospective upper bound rather
%   than an operational forecasting strategy.
%
% Prediction variables:
%   AR_Pred       [150, 360, 36]
%   ARIMA_Pred    [150, 360, 36]
%   SARIMA_Pred   [150, 360, 36]
%   SVM_Pred      [150, 360, 36]
%   RF_Pred       [150, 360, 36]
%   LSTM_Pred     [150, 360, 36]
%   SVMX_Pred     [150, 360, 36]
%   RFX_Pred      [150, 360, 36]
%   LSTMX_Pred    [150, 360, 36]
%
% Observations:
%   dGWS_mm       [150, 360, 252]
%   The final 36 months, 2022-01 to 2024-12, are extracted.
%
% Model order:
%   1. AR
%   2. ARIMA
%   3. SARIMA
%   4. SVM
%   5. RF
%   6. LSTM
%   7. SVMX
%   8. RFX
%   9. LSTMX
%
% Model groups:
%   1. Linear:
%      AR, ARIMA, SARIMA
%
%   2. Nonlinear:
%      SVM, RF, LSTM
%
%   3. Hydroclimatic-X:
%      SVMX, RFX, LSTMX
%
% Monthly gain categories:
%   1. No gain
%   2. Linear gain
%   3. Nonlinear gain
%   4. Hydroclimatic gain
%   5. Mixed gain
%
% Performance calculation:
%   1. Monthly oracle predictions are combined into a 36-month sequence.
%   2. NRMSE and TDA are calculated separately for 2022, 2023, and 2024.
%   3. The primary NRMSE and TDA are the means of the three annual values.
%   4. Combined 36-month NRMSE and TDA are also calculated as diagnostics.
%
% Figure:
%   Fig1:
%      Global mean annual NRMSE distribution of monthly oracle fusion.
%
% Outputs:
%   1. Fig1 PNG.
%   2. Global monthly-oracle performance statistics.
%   3. Monthly winner-model composition.
%   4. Monthly best-group and second-best-group composition.
%   5. Monthly gain-category composition.
%   6. Annual winner and gain-category composition.
%   7. Pixel-wise NRMSE and TDA statistics.
%   8. MAT file containing monthly winner, second-best model, group,
%      category, prediction, observation, and performance arrays.
%
% Tie handling:
%   If two models have exactly equal monthly absolute errors, MATLAB sort()
%   selects the model appearing first in the model order above.

