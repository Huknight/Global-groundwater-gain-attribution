%% ===================== Local functions =====================

function nrmseMap = calculateNRMSEMap( ...
    observed, ...
    predicted, ...
    validMask)

    completeMask = ...
        validMask & ...
        all(isfinite(observed), 3) & ...
        all(isfinite(predicted), 3);

    errorValues = ...
        observed - predicted;

    rmseMap = sqrt( ...
        mean(errorValues .^ 2, ...
        3, ...
        'omitnan'));

    observedRange = ...
        max(observed, [], 3) - ...
        min(observed, [], 3);

    nrmseMap = ...
        rmseMap ./ observedRange;

    nrmseMap(~completeMask) = NaN;
    nrmseMap(observedRange <= 0) = NaN;
end

function tdaMap = calculateTDAMap( ...
    observed, ...
    predicted, ...
    validMask)

    completeMask = ...
        validMask & ...
        all(isfinite(observed), 3) & ...
        all(isfinite(predicted), 3);

    observedDirection = sign( ...
        diff(observed, 1, 3));

    predictedDirection = sign( ...
        diff(predicted, 1, 3));

    directionAgreement = ...
        observedDirection == ...
        predictedDirection;

    tdaMap = mean( ...
        directionAgreement, ...
        3, ...
        'omitnan');

    tdaMap(~completeMask) = NaN;
end

function percentages = calculatePercentages(counts)

    counts = double(counts(:));

    totalCount = sum(counts);

    if totalCount <= 0

        percentages = nan(size(counts));
    else

        percentages = ...
            counts ./ totalCount .* 100;
    end
end