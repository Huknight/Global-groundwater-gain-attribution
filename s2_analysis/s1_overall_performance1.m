%
% ==================== 4. Additional Functions ====================

function [meanNRMSE, meanTDA] = computeGlobalMeans( ...
    resultFiles, validMask, nrmseVarNames, tdaVarNames)
% Compute the global mean NRMSE and TDA over all valid grid cells for a
% given group of model result files.

    nModel = numel(resultFiles);

    meanNRMSE = nan(1, nModel);
    meanTDA = nan(1, nModel);

    for i = 1:nModel
        thisFile = resultFiles{i};
        thisNRMSEVar = nrmseVarNames{i};
        thisTDAVar = tdaVarNames{i};

        D = load(thisFile, thisNRMSEVar, thisTDAVar);

        nrmseMap = double(D.(thisNRMSEVar));
        tdaMap = double(D.(thisTDAVar));

        meanNRMSE(i) = mean(nrmseMap(validMask));
        meanTDA(i) = mean(tdaMap(validMask));
    end
end

function displayPerformance( ...
    runName, modelNames, meanNRMSE, meanTDA)
% Print the global mean NRMSE and TDA of all models for one run.

    fprintf('\n================ %s ================\n', runName);

    for i = 1:numel(modelNames)
        fprintf('%-6s : Mean NRMSE = %.4f | Mean TDA = %.2f%%\n', ...
            modelNames{i}, ...
            meanNRMSE(i), ...
            meanTDA(i));
    end

    fprintf('===========================================================\n');
end

function plotMeanPerformance( ...
    meanNRMSE, meanTDA, modelNames, modelColors, ...
    figTitle, figFile, figPosition)
% Plot the global mean NRMSE and TDA of all models as paired bars and save
% the figure to a PNG file.

    % Number of models and x-axis positions
    nModel = numel(modelNames);
    x = 1:nModel;

    % Create figure
    fig = figure( ...
        'Color', 'w', ...
        'Position', figPosition);

    % Explicitly create an axes object.
    % This avoids dependence on the gca function.
    ax = axes( ...
        'Parent', fig);

    %% ---------- Left axis: mean NRMSE ----------

    yyaxis(ax, 'left');

    b1 = bar( ...
        ax, ...
        x - 0.18, ...
        meanNRMSE, ...
        0.35, ...
        'FaceColor', 'flat', ...
        'EdgeColor', 'k', ...
        'LineWidth', 0.8);

    % Assign model-specific colors
    for i = 1:nModel
        b1.CData(i, :) = modelColors(i, :);
    end

    ylabel(ax, 'Mean NRMSE');

    % NRMSE reference line
    yline( ...
        ax, ...
        0.26, ...
        '-b', ...
        'NRMSE = 0.26', ...
        'LineWidth', 1.2, ...
        'LabelHorizontalAlignment', 'left');

    %% ---------- Right axis: mean TDA ----------

    yyaxis(ax, 'right');

    b2 = bar( ...
        ax, ...
        x + 0.18, ...
        meanTDA, ...
        0.35, ...
        'FaceColor', 'flat', ...
        'EdgeColor', 'k', ...
        'LineWidth', 0.8);

    % Assign the same model-specific colors
    for i = 1:nModel
        b2.CData(i, :) = modelColors(i, :);
    end

    ylabel(ax, 'Mean TDA (%)');

    %% ---------- Shared axis settings ----------

    set(ax, ...
        'XTick', x, ...
        'XTickLabel', modelNames, ...
        'FontName', 'Times New Roman', ...
        'FontSize', 11);

    xlabel(ax, 'Models');
    title(ax, figTitle);

    % Ensure that both y axes are black
    yyaxis(ax, 'left');
    ax.YColor = [0, 0, 0];

    yyaxis(ax, 'right');
    ax.YColor = [0, 0, 0];

    %% ---------- Save figure ----------

    saveas(fig, figFile);
end
