%      original, UC1, or UC2 result files.
%   3. TDA values are assumed to have already been stored in percent units.
%   4. The global mean NRMSE/TDA is computed as a simple (unweighted) mean
%      over all valid grid cells, because NRMSE is a per-grid-cell model
%      evaluation metric and the spherical-area weighting is handled during
%      the 0.25-to-1-degree upscaling stage.
%
% ==================== 2. Centralized Parameter Settings ====================

