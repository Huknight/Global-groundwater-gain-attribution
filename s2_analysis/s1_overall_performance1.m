%
% ==================== 1. Code Description ====================
% Purpose:
%   Compare the global mean NRMSE and TDA of nine groundwater forecasting
%   models for the original run and two uncertainty-analysis repeat runs
%   (UC1 and UC2).
%
% Figures:
%   Fig1: Original-run global mean NRMSE and TDA.
%   Fig2: UC1 global mean NRMSE and TDA.
%   Fig3: UC2 global mean NRMSE and TDA.
%
