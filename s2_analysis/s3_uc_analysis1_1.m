%% s3_uc_analysis1_1.m
% Purpose:
%   Plot annual pixel-wise best NRMSE maps of the all-model fusion for:
%       1. 2022 test year
%       2. 2023 test year
%       3. 2024 test year
%
% Input:
%   s3_uc_analysis1_results.mat
%
% Figures:
%   Fig1: Global all-fusion best NRMSE distribution - 2022.
%   Fig2: Global all-fusion best NRMSE distribution - 2023.
%   Fig3: Global all-fusion best NRMSE distribution - 2024.
%
% Notes:
%   1. The all-model fusion selects the minimum annual NRMSE among the
%      nine candidate models at each pixel.
%   2. All three figures use the same color range and colormap to support
%      direct comparison across testing years.
%   3. Figure and font settings can be modified in the settings section.

clc;
clearvars;

%% ===================== Paths =====================

projectRoot = 'D:\P1_SKLGB\M_manuscript1_revised';

resultDir = fullfile(projectRoot, ...
    's3_darft', ...
    's1_analysis', ...
    's3_uc_analysis1_results');

inputMatFile = fullfile(resultDir, ...
    's3_uc_analysis1_results.mat');

outDir = resultDir;

if ~exist(outDir, 'dir')
    mkdir(outDir);
end

%% ===================== Load required results =====================

S = load(inputMatFile);

annualResult = S.annualResult;
testYears = double(S.testYears(:)');
lat = double(S.lat(:));
lon = double(S.lon(:));
commonTemporalMask = logical(S.commonTemporalMask);

clear S

%% ===================== Annual result setup =====================

nYear = numel(testYears);

%% ===================== Construct coordinate grids =====================

[Lon2D, Lat2D] = meshgrid(lon, lat);

%% ===================== Figure settings =====================

% Figure position and size
figPosition = [100, 100, 1000, 700];

% Shared color range for Fig1-Fig3
bestNRMSEClim = [0, 0.4];

% Shared colormap
bestNRMSECmap = jet(256);

% Font settings
% These values can be adjusted later.
fontName = 'Times New Roman';

titleFontSize = 15;
axisLabelFontSize = 13;
tickFontSize = 11;
colorbarFontSize = 11;
colorbarLabelFontSize = 12;

axisLineWidth = 0.8;

% Output resolution
outputResolution = 300;

%% ===================== Initialize annual statistics =====================

globalMeanBestNRMSE = nan(nYear, 1);
globalMedianBestNRMSE = nan(nYear, 1);

%% ===================== Plot Fig1-Fig3 =====================

for iYear = 1:nYear

    %% ---------- Extract annual all-fusion best NRMSE ----------

    bestNRMSEMap = double( ...
        annualResult(iYear).allFusion);

    % Retain only pixels included in the common temporal analysis.
    bestNRMSEMap(~commonTemporalMask) = NaN;

    %% ---------- Calculate global statistics ----------

    validValues = bestNRMSEMap(commonTemporalMask);

    globalMeanBestNRMSE(iYear) = mean(validValues);

    globalMedianBestNRMSE(iYear) = median(validValues);

    %% ---------- Figure information ----------

    figureNumber = iYear;

    figureTitle = sprintf( ...
        'Global all-fusion best NRMSE distribution - %d test year', ...
        testYears(iYear));

    figureFile = fullfile(outDir, ...
        sprintf( ...
        'Fig%d_Global_AllFusion_BestNRMSE_%d.png', ...
        figureNumber, ...
        testYears(iYear)));

    %% ---------- Create figure ----------

    fig = figure( ...
        'Color', ...
        'w', ...
        'Position', ...
        figPosition);

    ax = axes( ...
        'Parent', ...
        fig);

    %% ---------- Plot annual best NRMSE ----------

    hMap = pcolor( ...
        ax, ...
        Lon2D, ...
        Lat2D, ...
        bestNRMSEMap);

    set(hMap, ...
        'EdgeColor', ...
        'none');

    %% ---------- Axis settings ----------

    set(ax, ...
        'YDir', ...
        'normal', ...
        'FontName', ...
        fontName, ...
        'FontSize', ...
        tickFontSize, ...
        'LineWidth', ...
        axisLineWidth);

    axis(ax, 'equal');
    axis(ax, 'tight');

    xlabel( ...
        ax, ...
        'Longitude', ...
        'FontName', ...
        fontName, ...
        'FontSize', ...
        axisLabelFontSize);

    ylabel( ...
        ax, ...
        'Latitude', ...
        'FontName', ...
        fontName, ...
        'FontSize', ...
        axisLabelFontSize);

    title( ...
        ax, ...
        figureTitle, ...
        'FontName', ...
        fontName, ...
        'FontSize', ...
        titleFontSize, ...
        'FontWeight', ...
        'normal', ...
        'Interpreter', ...
        'none');

    %% ---------- Colormap and color range ----------

    colormap(ax, ...
        bestNRMSECmap);

    clim(ax, ...
        bestNRMSEClim);

    %% ---------- Colorbar ----------

    cb = colorbar(ax);

    cb.FontName = fontName;
    cb.FontSize = colorbarFontSize;

    ylabel( ...
        cb, ...
        'Best NRMSE', ...
        'FontName', ...
        fontName, ...
        'FontSize', ...
        colorbarLabelFontSize);

    %% ---------- Export figure ----------

    exportgraphics( ...
        fig, ...
        figureFile, ...
        'Resolution', ...
        outputResolution);

    clear bestNRMSEMap validValues
end

%% ===================== Create annual statistics table =====================

annualBestNRMSETable = table( ...
    testYears(:), ...
    globalMeanBestNRMSE, ...
    globalMedianBestNRMSE, ...
    repmat(nnz(commonTemporalMask), nYear, 1), ...
    'VariableNames', { ...
    'TestYear', ...
    'GlobalMeanBestNRMSE', ...
    'GlobalMedianBestNRMSE', ...
    'ValidPixelCount'});

%% ===================== Display statistics =====================

fprintf('\n');
fprintf('====================================================================\n');
fprintf('           ANNUAL ALL-FUSION BEST NRMSE STATISTICS\n');
fprintf('====================================================================\n');

fprintf('%-10s %-20s %-20s %-15s\n', ...
    'TestYear', ...
    'Mean best NRMSE', ...
    'Median best NRMSE', ...
    'Valid pixels');

fprintf('--------------------------------------------------------------------\n');

for iYear = 1:nYear

    fprintf('%-10d %-20.6f %-20.6f %-15d\n', ...
        testYears(iYear), ...
        globalMeanBestNRMSE(iYear), ...
        globalMedianBestNRMSE(iYear), ...
        nnz(commonTemporalMask));
end

fprintf('====================================================================\n');

disp(' ');
disp(annualBestNRMSETable);

%% ===================== Save statistics =====================

csvFile = fullfile(outDir, ...
    's3_uc_analysis1_1_Annual_BestNRMSE_Statistics.csv');

writetable( ...
    annualBestNRMSETable, ...
    csvFile);

matFile = fullfile(outDir, ...
    's3_uc_analysis1_1_results.mat');

save(matFile, ...
    'testYears', ...
    'globalMeanBestNRMSE', ...
    'globalMedianBestNRMSE', ...
    'annualBestNRMSETable', ...
    'commonTemporalMask', ...
    'lat', ...
    'lon', ...
    'figPosition', ...
    'bestNRMSEClim', ...
    'bestNRMSECmap');

%% ===================== Completion message =====================

fprintf('\nCompleted: annual all-fusion best NRMSE maps.\n');
fprintf('Output directory:\n%s\n', outDir);