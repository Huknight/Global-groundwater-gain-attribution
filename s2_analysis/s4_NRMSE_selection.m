    thisWinnerIdx(~commonAnalysisMask) = NaN;

    allFusionAnnualNRMSE(:, :, iYear) = ...
        thisFusionNRMSE;

    bestAnnualModelIdx(:, :, iYear) = ...
        thisWinnerIdx;
end

