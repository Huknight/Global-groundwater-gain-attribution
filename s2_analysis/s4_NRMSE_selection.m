    dataRoot, ...
    '02_spatial_temporal_processing');

linearDir = fullfile( ...
    dataRoot, ...
    '04_linear_models');

nonlinearDir = fullfile( ...
    dataRoot, ...
    '05_nonlinear_models');

nonlinearXDir = fullfile( ...
    dataRoot, ...
    '06_nonlinear_x_models');

maskFile = fullfile( ...
    dataRoot, ...
    '03_master_database', ...
    'GLDAS_common_valid_mask_1deg_200401_202412.mat');

observationFile = fullfile( ...
    spatialTemporalDir, ...
    'GLDAS_DA_CLSM10_dGWS_monthend_200401_202412.mat');

outDir = fullfile( ...
    projectRoot, ...
    's3_darft', ...
    's1_analysis', ...
    's4_model_selection_results');

