predictionVarNames = cell(nModel, 1);

for iModel = 1:nModel

    meanNRMSEVarNames{iModel} = ...
        [modelLabels{iModel}, '_NRMSE_mean'];

    annualNRMSEVarNames{iModel} = ...
        [modelLabels{iModel}, '_NRMSE'];

    predictionVarNames{iModel} = ...
        [modelLabels{iModel}, '_Pred'];
