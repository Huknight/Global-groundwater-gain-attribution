%% ========================================================================
%% Local function: sample and plot one case
%% ========================================================================

function [R, selectionTable] = sampleAndPlotCase( ...
    figureNumber, ...
    caseLabel, ...
    testYear, ...
    nrmseMap, ...
    bestModelIdx, ...
    timeIndex, ...
    figureTitle, ...
    figureFile, ...
    analysisMask, ...
    observedTest, ...
    predictionStack, ...
    PredYM, ...
    modelLabels, ...
    lat, ...
    lon, ...
    binLower, ...
    binUpper, ...
    randomSeed, ...
    settings)

    nPoint = numel(binLower);

    nLat = size(analysisMask, 1);
    nLon = size(analysisMask, 2);

    nrmseMap = double(nrmseMap);
    bestModelIdx = double(bestModelIdx);

    caseYM = PredYM(timeIndex);

    timeAxis = ymToDatetime( ...
        caseYM);

    %% ===================== Random pixel sampling =====================

    rng( ...
        randomSeed, ...
        'twister');

    isSelected = false(nPoint, 1);

    candidatePixelCount = zeros(nPoint, 1);

    selectedLinearIndex = nan(nPoint, 1);
    selectedGridRow = nan(nPoint, 1);
    selectedGridColumn = nan(nPoint, 1);

    selectedLatitude = nan(nPoint, 1);
    selectedLongitude = nan(nPoint, 1);

    selectedNRMSE = nan(nPoint, 1);
    selectedModelIdx = nan(nPoint, 1);
    selectedModelName = strings(nPoint, 1);

    predictionSeries = cell(nPoint, 1);
    observationSeries = cell(nPoint, 1);

    for iPoint = 1:nPoint

        candidateMask = ...
            analysisMask & ...
            nrmseMap >= binLower(iPoint) & ...
            nrmseMap < binUpper(iPoint);

        candidateIndex = find( ...
            candidateMask);

        candidatePixelCount(iPoint) = ...
            numel(candidateIndex);

        if isempty(candidateIndex)

            warning([ ...
                'Fig%d: no candidate pixel was found in NRMSE ', ...
                'interval [%.2f, %.2f).'], ...
                figureNumber, ...
                binLower(iPoint), ...
                binUpper(iPoint));

            continue;
        end

        randomPosition = randi( ...
            numel(candidateIndex));

        selectedIndex = ...
            candidateIndex(randomPosition);

        [thisGridRow, thisGridColumn] = ind2sub( ...
            [nLat, nLon], ...
            selectedIndex);

        thisModelIdx = ...
            bestModelIdx( ...
            thisGridRow, ...
            thisGridColumn);

        thisModelIdx = round( ...
            thisModelIdx);

        thisPrediction = squeeze( ...
            predictionStack( ...
            thisGridRow, ...
            thisGridColumn, ...
            timeIndex, ...
            thisModelIdx));

        thisObservation = squeeze( ...
            observedTest( ...
            thisGridRow, ...
            thisGridColumn, ...
            timeIndex));

        thisPrediction = ...
            thisPrediction(:);

        thisObservation = ...
            thisObservation(:);

        isSelected(iPoint) = true;

        selectedLinearIndex(iPoint) = ...
            selectedIndex;

        selectedGridRow(iPoint) = ...
            thisGridRow;

        selectedGridColumn(iPoint) = ...
            thisGridColumn;

        selectedLatitude(iPoint) = ...
            lat(thisGridRow);

        selectedLongitude(iPoint) = ...
            lon(thisGridColumn);

        selectedNRMSE(iPoint) = ...
            nrmseMap( ...
            thisGridRow, ...
            thisGridColumn);

        selectedModelIdx(iPoint) = ...
            thisModelIdx;

        selectedModelName(iPoint) = ...
            string(modelLabels{thisModelIdx});

        predictionSeries{iPoint} = ...
            thisPrediction;

        observationSeries{iPoint} = ...
            thisObservation;

        fprintf([ ...
            'Point %02d | [%.2f, %.2f) | candidates=%d | ', ...
            'NRMSE=%.4f | %s | row=%d | column=%d\n'], ...
            iPoint, ...
            binLower(iPoint), ...
            binUpper(iPoint), ...
            candidatePixelCount(iPoint), ...
            selectedNRMSE(iPoint), ...
            char(selectedModelName(iPoint)), ...
            thisGridRow, ...
            thisGridColumn);
    end

%% ===================== Create 5-by-4 figure =====================

% Create an independent MATLAB figure window for Fig1-Fig4.
% Re-running the script clears only the corresponding numbered figure.

    fig = figure(figureNumber);

    clf(fig);

    set(fig, ...
        'Color', ...
        'w', ...
        'Position', ...
        settings.figurePosition, ...
        'Name', ...
        sprintf('Fig%d - %s', figureNumber, caseLabel), ...
        'NumberTitle', ...
        'off');

    figure(fig);

    firstValidAxes = [];
    legendHandles = [];

    for iPoint = 1:nPoint

        figure(fig);

        ax = subplot( ...
            5, ...
            4, ...
            iPoint);

        if ~isSelected(iPoint)

            axis(ax, 'off');

            title( ...
                ax, ...
                sprintf( ...
                'Point %02d | No sample', ...
                iPoint), ...
                'FontName', ...
                settings.fontName, ...
                'FontSize', ...
                settings.panelTitleFontSize, ...
                'FontWeight', ...
                'normal');

            continue;
        end

        thisPrediction = ...
            predictionSeries{iPoint};

        thisObservation = ...
            observationSeries{iPoint};

        hPrediction = plot( ...
            ax, ...
            timeAxis, ...
            thisPrediction, ...
            '-', ...
            'Color', ...
            settings.predictionColor, ...
            'LineWidth', ...
            settings.curveLineWidth);

        hold(ax, 'on');

        hObservation = plot( ...
            ax, ...
            timeAxis, ...
            thisObservation, ...
            '-', ...
            'Color', ...
            settings.observationColor, ...
            'LineWidth', ...
            settings.curveLineWidth);

        hold(ax, 'off');

        if isempty(firstValidAxes)

            firstValidAxes = ax;

            legendHandles = [ ...
                hPrediction, ...
                hObservation];
        end

        grid(ax, 'on');
        box(ax, 'on');

        set(ax, ...
            'FontName', ...
            settings.fontName, ...
            'FontSize', ...
            settings.axisFontSize, ...
            'LineWidth', ...
            settings.axisLineWidth);

        title( ...
            ax, ...
            sprintf( ...
            'Point %02d | NRMSE: %.3f | %s', ...
            iPoint, ...
            selectedNRMSE(iPoint), ...
            char(selectedModelName(iPoint))), ...
            'FontName', ...
            settings.fontName, ...
            'FontSize', ...
            settings.panelTitleFontSize, ...
            'FontWeight', ...
            'normal', ...
            'Interpreter', ...
            'none');

        %% ---------- Time-axis settings ----------

        if numel(timeIndex) == 36

            xlim(ax, [ ...
                datetime(2022, 1, 1), ...
                datetime(2025, 1, 1)]);

            xticks(ax, ...
                datetime(2022:2025, 1, 1));

            xticklabels(ax, { ...
                '2022', ...
                '2023', ...
                '2024', ...
                '2025'});

        elseif numel(timeIndex) == 12

            thisYear = floor( ...
                caseYM(1) ./ 100);

            quarterPositions = [ ...
                1, ...
                4, ...
                7, ...
                10];

            xlim(ax, [ ...
                datetime(thisYear, 1, 1), ...
                datetime(thisYear + 1, 1, 1)]);

            xticks(ax, ...
                timeAxis(quarterPositions));

            xticklabels(ax, { ...
                'Jan', ...
                'Apr', ...
                'Jul', ...
                'Oct'});

        else

            xlim(ax, [ ...
                timeAxis(1), ...
                timeAxis(end)]);
        end

        %% ---------- Curve-dependent y-axis range ----------

        combinedSeries = [ ...
            thisPrediction; ...
            thisObservation];

        yMinimum = min( ...
            combinedSeries, ...
            [], ...
            'omitnan');

        yMaximum = max( ...
            combinedSeries, ...
            [], ...
            'omitnan');

        if isfinite(yMinimum) && isfinite(yMaximum)

            if yMaximum > yMinimum

                yPadding = ...
                    0.05 .* ...
                    (yMaximum - yMinimum);

            else

                yPadding = max( ...
                    1, ...
                    abs(yMaximum) .* 0.10);
            end

            ylim(ax, [ ...
                yMinimum - yPadding, ...
                yMaximum + yPadding]);
        end

        %% ---------- Axis labels ----------

        if iPoint > 16

            xlabel( ...
                ax, ...
                'Time', ...
                'FontName', ...
                settings.fontName, ...
                'FontSize', ...
                settings.axisLabelFontSize);
        end

        if mod(iPoint - 1, 4) == 0

            ylabel( ...
                ax, ...
                '\DeltaGWS', ...
                'FontName', ...
                settings.fontName, ...
                'FontSize', ...
                settings.axisLabelFontSize);
        end
    end

    %% ===================== Shared title =====================

    sgtitle( ...
        fig, ...
        figureTitle, ...
        'FontName', ...
        settings.fontName, ...
        'FontSize', ...
        settings.superTitleFontSize, ...
        'FontWeight', ...
        'bold', ...
        'Interpreter', ...
        'none');

