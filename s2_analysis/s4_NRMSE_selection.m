%% ========================================================================
%% Local function: build YYYYMM vector
%% ========================================================================

function ym = buildYMVector( ...
    startYear, ...
    startMonth, ...
    endYear, ...
    endMonth)

    firstTime = datetime( ...
        startYear, ...
        startMonth, ...
        1);

    finalTime = datetime( ...
        endYear, ...
        endMonth, ...
        1);

    timeVector = ...
        (firstTime:calmonths(1):finalTime)';

    ym = ...
        year(timeVector) .* 100 + ...
        month(timeVector);

    ym = double(ym(:));
end

%% ========================================================================
%% Local function: normalize year-month values
%% ========================================================================

function ym = normalizeYM(inputValue)

    inputValue = inputValue(:);

    if isdatetime(inputValue)

        ym = ...
            year(inputValue) .* 100 + ...
            month(inputValue);

        ym = double(ym(:));
        return;
    end

    if isnumeric(inputValue)

        numericValue = double( ...
            inputValue(:));

        % Convert MATLAB datenums when necessary.
        if all( ...
                numericValue > 7e5 & ...
                numericValue < 8e5)

            timeValue = datetime( ...
                numericValue, ...
                'ConvertFrom', ...
                'datenum');

            ym = ...
                year(timeValue) .* 100 + ...
                month(timeValue);

        else

            ym = numericValue;
        end

        ym = double(ym(:));
        return;
    end

    if iscellstr(inputValue) || ...
            isstring(inputValue)

        stringValue = string( ...
            inputValue(:));

        stringValue = erase( ...
            stringValue, ...
            {'-', '/', '_'});

        ym = str2double( ...
            stringValue);

        ym = double(ym(:));
        return;
    end

    error('Unsupported year-month variable type.');
end

%% ========================================================================
%% Local function: convert YYYYMM to datetime
%% ========================================================================

function timeVector = ymToDatetime(ym)

    ym = double(ym(:));

    yearValue = floor( ...
        ym ./ 100);

    monthValue = ...
        ym - yearValue .* 100;

    timeVector = datetime( ...
        yearValue, ...
        monthValue, ...
        1);
end