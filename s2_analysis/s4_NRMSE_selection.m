%% s4_NRMSE_selection.m
% Purpose:
%   Plot observed and all-fusion winner prediction curves across twenty
%   increasing NRMSE intervals for four evaluation cases:
%
%   Fig1:
%       Winner selected using the three-year mean NRMSE.
%       The fixed winner model is plotted over the full 2022-2024 period.
%
%   Fig2:
%       Winner selected independently using the 2022 NRMSE.
%       Only the 2022 prediction and observation are plotted.
%
%   Fig3:
%       Winner selected independently using the 2023 NRMSE.
%       Only the 2023 prediction and observation are plotted.
%
%   Fig4:
%       Winner selected independently using the 2024 NRMSE.
%       Only the 2024 prediction and observation are plotted.
%
% Sampling intervals:
%   Point 01: [0.05, 0.06)
%   Point 02: [0.06, 0.07)
%   ...
%   Point 20: [0.24, 0.25)
%
% Prediction period:
%   All MODEL_Pred variables are assumed to contain 36 chronological
%   monthly predictions from 2022-01 to 2024-12.
%
% Prediction time variables:
%   The 36 prediction layers of every model file are explicitly
%   interpreted as 202201-202412 according to the experiment design.
%
% Observation period:
%   The dGWS_mm observation sequence is matched using the ym variable.
%   The code explicitly extracts ym = 202201-202412.
%
% Output directory:
%   D:\P1_SKLGB\M_manuscript1_revised\s3_darft\s1_analysis\
%   s4_model_selection_results
%
% Required model variables:
%   MODEL_NRMSE_mean    [latitude, longitude]
%   MODEL_NRMSE         [latitude, longitude, 3]
%   MODEL_Pred          [latitude, longitude, 36]
%
% Model order:
%   1. AR
%   2. ARIMA
%   3. SARIMA
%   4. SVM
%   5. RF
%   6. LSTM
%   7. SVMX
%   8. RFX
%   9. LSTMX

