%% ===================== Construct a common analysis mask =====================

% The same pixel domain is used for all four figures. A retained pixel must:
%
%   1. belong to CommonValid;
%   2. have finite mean NRMSE for all nine models;
%   3. have finite annual NRMSE for all nine models and all three years;
%   4. have finite observations for all 36 months;
%   5. have finite predictions for all nine models and all 36 months.

commonAnalysisMask = CommonValid;

commonAnalysisMask = ...
    commonAnalysisMask & ...
    all(isfinite(meanNRMSEStack), 3);

for iYear = 1:nYear

    thisAnnualNRMSEStack = ...
        annualNRMSEStack(:, :, :, iYear);

    commonAnalysisMask = ...
        commonAnalysisMask & ...
        all(isfinite(thisAnnualNRMSEStack), 3);
end

commonAnalysisMask = ...
    commonAnalysisMask & ...
    all(isfinite(observedTest), 3);

for iModel = 1:nModel

    thisPrediction = ...
        predictionStack(:, :, :, iModel);

    commonAnalysisMask = ...
        commonAnalysisMask & ...
        all(isfinite(thisPrediction), 3);
end

nCommonPixel = nnz(commonAnalysisMask);

