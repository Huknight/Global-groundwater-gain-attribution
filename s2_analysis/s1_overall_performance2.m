%% s1_overall_performance2.m

clc;
clearvars;

%
% ==================== 1. Code Description ====================
% Purpose:
%   Plot the global NRMSE maps of nine groundwater forecasting models
%   using the original-run results.
%
% Figures:
%   Fig1-Fig9: Global NRMSE of AR, ARIMA, SARIMA, SVM, RF, LSTM, SVMX,
%   RFX, and LSTMX models, respectively.
%
% Outputs:
%   Nine PNG figures and one MAT result file.
%
% Data source:
%   All model results are read from the revised master database
%   (M_manuscript1_revised\s1_master_database), in which the 0.25-degree
%   to 1-degree upscaling has been corrected with spherical-area weights.
%
% Notes:
%   1. Only the original-run results are used.
%   2. UC1 and UC2 results are not included in this script.
%   3. All figures use the same position, color scale, and colormap.
%
% ==================== 2. Centralized Parameter Settings ====================

% ------------------------------ Paths ------------------------------
projectRoot = 'D:\P1_SKLGB\M_manuscript1_revised';

dataRoot = fullfile(projectRoot, 's1_master_database');

maskFile = fullfile(dataRoot, ...
    '03_master_database', ...
    'GLDAS_common_valid_mask_1deg_200401_202412.mat');

linearDir = fullfile(dataRoot, '04_linear_models');
nonlinearDir = fullfile(dataRoot, '05_nonlinear_models');
nonlinearXDir = fullfile(dataRoot, '06_nonlinear_x_models');

outDir = fullfile(projectRoot, ...
    's3_darft', ...
    's1_analysis', ...
    's1_overall_performance2_results');

if ~exist(outDir, 'dir')
    mkdir(outDir);
end

% ----------------------- Model result files -----------------------
% Note: the revised SARIMA result file has no "_d0" suffix.

% ---------- Linear models ----------
arFile = fullfile(linearDir, ...
    'AR_univariate_global_200401_202412.mat');

arimaFile = fullfile(linearDir, ...
    'ARIMA_univariate_global_200401_202412_d0.mat');

sarimaFile = fullfile(linearDir, ...
    'SARIMA_univariate_global_200401_202412.mat');

% ---------- Nonlinear models ----------
svmFile = fullfile(nonlinearDir, ...
    'SVM_univariate_global_200401_202412.mat');

rfFile = fullfile(nonlinearDir, ...
    'RF_univariate_global_200401_202412.mat');

lstmFile = fullfile(nonlinearDir, ...
    'LSTM_univariate_global_200401_202412.mat');

% ---------- Nonlinear-X models ----------
svmxFile = fullfile(nonlinearXDir, ...
    'SVMX_multivariate_global_200401_202412.mat');

rfxFile = fullfile(nonlinearXDir, ...
    'RFX_multivariate_global_200401_202412.mat');

lstmxFile = fullfile(nonlinearXDir, ...
    'LSTMX_multivariate_global_200401_202412.mat');

% ------------------ Model names and variable names ------------------
modelNames = { ...
    'AR', ...
    'ARIMA', ...
    'SARIMA', ...
    'SVM', ...
    'RF', ...
    'LSTM', ...
    'SVMX', ...
    'RFX', ...
    'LSTMX'};

modelFiles = { ...
    arFile, ...
    arimaFile, ...
    sarimaFile, ...
    svmFile, ...
    rfFile, ...
    lstmFile, ...
    svmxFile, ...
    rfxFile, ...
    lstmxFile};

nrmseVarNames = { ...
    'AR_NRMSE_mean', ...
    'ARIMA_NRMSE_mean', ...
    'SARIMA_NRMSE_mean', ...
    'SVM_NRMSE_mean', ...
    'RF_NRMSE_mean', ...
    'LSTM_NRMSE_mean', ...
    'SVMX_NRMSE_mean', ...
    'RFX_NRMSE_mean', ...
    'LSTMX_NRMSE_mean'};

nModel = numel(modelNames);

% ------------------------- Figure settings -------------------------
% Figure position and size
figPosition = [100, 100, 1000, 700];

% Shared color range
nrmseColorLimits = [0, 0.4];

% Shared colormap
nrmseColormap = jet(256);

% Font settings
fontName = 'Times New Roman';

titleFontSize = 16;
axisLabelFontSize = 13;
tickFontSize = 13;
colorbarFontSize = 13;
colorbarLabelFontSize = 13;

% Output resolution
outputResolution = 300;

%
% ==================== 3. Main Body ====================

% ------------------- Load the common valid mask -------------------
D_mask = load(maskFile, 'CommonValid');
validMask = logical(D_mask.CommonValid);
clear D_mask

% ------------------- Load latitude and longitude -------------------
% Coordinates are read from the AR result file.
D_coord = load(arFile, 'lat', 'lon');
lat = double(D_coord.lat(:));
lon = double(D_coord.lon(:));
clear D_coord

% Construct two-dimensional longitude and latitude grids
[Lon2D, Lat2D] = meshgrid(lon, lat);

% ------------------- Load original-run NRMSE maps -------------------
NRMSE_maps = nan(size(validMask, 1), size(validMask, 2), nModel);

for iModel = 1:nModel
    thisFile = modelFiles{iModel};
    thisVariable = nrmseVarNames{iModel};

    D_model = load(thisFile, thisVariable);
    thisNRMSE = double(D_model.(thisVariable));

    % Remove pixels outside the common valid domain
    thisNRMSE(~validMask) = NaN;

    NRMSE_maps(:, :, iModel) = thisNRMSE;

    clear D_model thisNRMSE
end

% ------------------- Plot Fig1-Fig9 -------------------
for iModel = 1:nModel
    modelName = modelNames{iModel};
    nrmseMap = NRMSE_maps(:, :, iModel);

    figureTitle = sprintf('Global NRMSE of %s model', modelName);

    figureFile = fullfile(outDir, ...
        sprintf('Fig%d_Global_NRMSE_%s_model.png', iModel, modelName));

    plotGlobalNRMSEMap( ...
        iModel, ...
        Lon2D, ...
        Lat2D, ...
        nrmseMap, ...
        figureTitle, ...
        figureFile, ...
        figPosition, ...
        nrmseColorLimits, ...
        nrmseColormap, ...
        fontName, ...
        titleFontSize, ...
        axisLabelFontSize, ...
        tickFontSize, ...
        colorbarFontSize, ...
        colorbarLabelFontSize, ...
        outputResolution);
end

% ------------------- Save calculation results -------------------
resultFile = fullfile(outDir, 's1_overall_performance2_results.mat');

save(resultFile, ...
    'modelNames', ...
    'modelFiles', ...
    'nrmseVarNames', ...
    'NRMSE_maps', ...
    'validMask', ...
    'lat', ...
    'lon', ...
    'nrmseColorLimits', ...
    'figPosition');

disp('Completed: global NRMSE maps for all nine models.');
disp(['Output directory: ', outDir]);

%
% ==================== 4. Additional Functions ====================

function plotGlobalNRMSEMap( ...
    figureNumber, ...
    Lon2D, ...
    Lat2D, ...
    nrmseMap, ...
    figureTitle, ...
    figureFile, ...
    figPosition, ...
    nrmseColorLimits, ...
    nrmseColormap, ...
    fontName, ...
    titleFontSize, ...
    axisLabelFontSize, ...
    tickFontSize, ...
    colorbarFontSize, ...
    colorbarLabelFontSize, ...
    outputResolution)

    %% ---------- Create figure ----------

    fig = figure(figureNumber);
    clf(fig);

    set(fig, ...
        'Color', 'w', ...
        'Position', figPosition);

    % Explicitly create an axes object
    ax = axes('Parent', fig);

    %% ---------- Plot global NRMSE map ----------

    pcolor(ax, Lon2D, Lat2D, nrmseMap);
    shading(ax, 'flat');

    %% ---------- Axis settings ----------

    set(ax, ...
        'YDir', 'normal', ...
        'FontName', fontName, ...
        'FontSize', tickFontSize, ...
        'LineWidth', 0.8);

    axis(ax, 'equal');
    axis(ax, 'tight');

    xlim(ax, [min(Lon2D(:)), max(Lon2D(:))]);
    ylim(ax, [min(Lat2D(:)), max(Lat2D(:))]);

    xlabel(ax, 'Longitude', ...
        'FontName', fontName, ...
        'FontSize', axisLabelFontSize);

    ylabel(ax, 'Latitude', ...
        'FontName', fontName, ...
        'FontSize', axisLabelFontSize);

    title(ax, figureTitle, ...
        'FontName', fontName, ...
        'FontSize', titleFontSize, ...
        'FontWeight', 'normal');

    %% ---------- Colormap and color limits ----------

    colormap(ax, nrmseColormap);
    clim(ax, nrmseColorLimits);

    %% ---------- Colorbar settings ----------

    cb = colorbar(ax);
    cb.FontName = fontName;
    cb.FontSize = colorbarFontSize;

    ylabel(cb, 'NRMSE', ...
        'FontName', fontName, ...
        'FontSize', colorbarLabelFontSize);

    %% ---------- Export figure ----------

    exportgraphics(fig, figureFile, 'Resolution', outputResolution);
end
