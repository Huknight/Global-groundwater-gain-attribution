%% s4_model_selection.m
% Purpose:
%   Evaluate candidate-model testing priorities within two AR-NRMSE
%   screening ranges.
%
%   3 stochastic runs:
%       1. Original
%       2. UC1
%       3. UC2
%
%   3 independent testing years:
%       1. 2022
%       2. 2023
%       3. 2024
%
%   A separate screening table is generated for each run-year
%   combination, resulting in nine case tables per screening range.
%
% Screening ranges:
%   1. AR NRMSE in [0.10, 0.25)
%   2. AR NRMSE in [0.10, 0.33)
%
%   Pixels where the annual all-model fusion does not improve upon AR
%   are excluded from both ranges.
%
% Statistics for each model except AR:
%   1. Number of pixels where the model improves upon AR.
%   2. Percentage of computation-region pixels where the model improves
%      upon AR.
%   3. Mean and median NRMSE reduction relative to AR, calculated only
%      over pixels where the corresponding model improves upon AR.
%   4. Mean and median NRMSE gap relative to the annual all-model
%      fusion best, calculated over the same positive-gain pixels.
%
% Weighted final table:
%   The nine cases are aggregated using their underlying pixel samples:
%
%   GainPixels:
%       Total positive-gain pixel-evaluations across all nine cases.
%
%   GainPixelsPct:
%       Total positive-gain pixel-evaluations divided by the total
%       number of computation-region pixel-evaluations across all
%       nine cases.
%
%   Mean reductions and gaps:
%       Pooled means, equivalent to weighting each case by its number
%       of positive-gain pixels.
%
%   Median reductions and gaps:
%       Recalculated from the pooled positive-gain samples. Medians are
%       not obtained by averaging the nine case-level medians.
%
% Important:
%   AR, ARIMA, and SARIMA are deterministic and use the same files in
%   the Original, UC1, and UC2 analyses.
%
%   SVM, RF, LSTM, SVMX, RFX, and LSTMX use the corresponding Original,
%   UC1, and UC2 result files.
%
% Required model variables:
%   MODEL_NRMSE    [latitude, longitude, 3]
%   CommonValid    mask file
%
% Model order:
%   1. AR
%   2. ARIMA
%   3. SARIMA
%   4. SVM
%   5. RF
%   6. LSTM
%   7. SVMX
%   8. RFX
%   9. LSTMX
%
% Output directory:
%   D:\P1_SKLGB\M_manuscript1_revised\s3_darft\s1_analysis\
%   s4_model_selection_results
%
% Main outputs (per screening range):
%   1. s4_model_selection_9_case_tables_<range>.xlsx
%   2. s4_model_selection_weighted_table_<range>.xlsx
%   3. Nine individual CSV tables
%   4. Region_Screening_Summary_<range>.csv
%
% Shared output:
%   5. s4_model_selection_results.mat

clc;
clearvars;
close all;

%% ===================== Paths =====================

projectRoot = 'D:\P1_SKLGB\M_manuscript1_revised';

dataRoot = fullfile( ...
    projectRoot, ...
    's1_master_database');

linearDir = fullfile( ...
    dataRoot, ...
    '04_linear_models');

nonlinearDir = fullfile( ...
    dataRoot, ...
    '05_nonlinear_models');

nonlinearXDir = fullfile( ...
    dataRoot, ...
    '06_nonlinear_x_models');

maskFile = fullfile( ...
    dataRoot, ...
    '03_master_database', ...
    'GLDAS_common_valid_mask_1deg_200401_202412.mat');

outDir = fullfile( ...
    projectRoot, ...
    's3_darft', ...
    's1_analysis', ...
    's4_model_selection_results');

if ~exist(outDir, 'dir')
    mkdir(outDir);
end

%% ===================== Screening settings =====================

% Two screening ranges. The lower bound is shared; the upper bound
% distinguishes the narrower and the expanded range.

rangeLabels = { ...
    '[0.10,0.25)'; ...
    '[0.10,0.33)'};

rangeTags = { ...
    '0.10to0.25'; ...
    '0.10to0.33'};

lowerARThreshold = ...
    0.10 .* ones(numel(rangeLabels), 1);

upperARThreshold = [ ...
    0.25; ...
    0.33];

% Numerical tolerance for zero-gain and positive-gain comparisons.
tolerance = 1e-12;

% When true, all nine run-year tables use exactly the same spatial
% domain. A pixel must contain finite annual NRMSE values for all nine
% models, all three runs, and all three testing years.
%
% This is recommended because differences among tables then reflect
% evaluation year and stochastic training rather than missing-data
% domains.
useStrictCommonMaskAcrossAllCases = true;

%% ===================== Model definitions =====================

modelLabels = { ...
    'AR'; ...
    'ARIMA'; ...
    'SARIMA'; ...
    'SVM'; ...
    'RF'; ...
    'LSTM'; ...
    'SVMX'; ...
    'RFX'; ...
    'LSTMX'};

nModel = numel(modelLabels);

annualNRMSEVarNames = cell(nModel, 1);

for iModel = 1:nModel

    annualNRMSEVarNames{iModel} = ...
        [modelLabels{iModel}, '_NRMSE'];
end

% AR is the benchmark and is excluded from the reported statistics.
targetModelIndices = 2:nModel;

targetModelNames = ...
    modelLabels(targetModelIndices);

nTargetModel = ...
    numel(targetModelIndices);

%% ===================== Run and year definitions =====================

runNames = { ...
    'Original'; ...
    'UC1'; ...
    'UC2'};

runSuffixes = { ...
    ''; ...
    '_uc1'; ...
    '_uc2'};

testYears = [2022, 2023, 2024];

nRun = numel(runNames);
nYear = numel(testYears);
nCase = nRun .* nYear;

%% ===================== Model result files =====================

% Deterministic linear models, shared by all three runs.

linearFiles = { ...
    fullfile( ...
    linearDir, ...
    'AR_univariate_global_200401_202412.mat'); ...

    fullfile( ...
    linearDir, ...
    'ARIMA_univariate_global_200401_202412_d0.mat'); ...

    fullfile( ...
    linearDir, ...
    'SARIMA_univariate_global_200401_202412.mat')};

% Nonlinear and nonlinear-augmented model stems. The run suffix is
% appended before the file extension.

nonlinearDirList = { ...
    nonlinearDir; ...
    nonlinearDir; ...
    nonlinearDir; ...
    nonlinearXDir; ...
    nonlinearXDir; ...
    nonlinearXDir};

nonlinearStems = { ...
    'SVM_univariate_global_200401_202412'; ...
    'RF_univariate_global_200401_202412'; ...
    'LSTM_univariate_global_200401_202412'; ...
    'SVMX_multivariate_global_200401_202412'; ...
    'RFX_multivariate_global_200401_202412'; ...
    'LSTMX_multivariate_global_200401_202412'};

resultFileGroups = cell(nRun, nModel);

for iRun = 1:nRun

    for iModel = 1:nModel

        if iModel <= numel(linearFiles)

            resultFileGroups{iRun, iModel} = ...
                linearFiles{iModel};

        else

            iStem = ...
                iModel - numel(linearFiles);

            resultFileGroups{iRun, iModel} = fullfile( ...
                nonlinearDirList{iStem}, ...
                [nonlinearStems{iStem}, ...
                runSuffixes{iRun}, ...
                '.mat']);
        end
    end
end

%% ===================== Validate files =====================

if ~isfile(maskFile)

    error('Common valid-mask file was not found:\n%s', ...
        maskFile);
end

for iRun = 1:nRun

    for iModel = 1:nModel

        thisFile = resultFileGroups{iRun, iModel};

        if ~isfile(thisFile)

            error([ ...
                'Result file was not found for run %s, model %s:\n%s'], ...
                runNames{iRun}, ...
                modelLabels{iModel}, ...
                thisFile);
        end
    end
end

%% ===================== Load common valid mask =====================

D_mask = load( ...
    maskFile, ...
    'CommonValid');

if ~isfield(D_mask, 'CommonValid')

    error('Variable "CommonValid" was not found in:\n%s', ...
        maskFile);
end

baseValidMask = logical( ...
    D_mask.CommonValid);

clear D_mask

nLatitude = size(baseValidMask, 1);
nLongitude = size(baseValidMask, 2);

fprintf('\nBase CommonValid pixels: %d\n', ...
    nnz(baseValidMask));

%% ===================== Load all annual NRMSE arrays =====================

% Dimensions:
%   latitude x longitude x model x testing year x run

annualNRMSEAll = nan( ...
    nLatitude, ...
    nLongitude, ...
    nModel, ...
    nYear, ...
    nRun);

fprintf('\nLoading annual NRMSE arrays...\n');

for iRun = 1:nRun

    fprintf('\nRun: %s\n', ...
        runNames{iRun});

    for iModel = 1:nModel

        thisFile = resultFileGroups{iRun, iModel};
        thisVariable = annualNRMSEVarNames{iModel};

        fileVariableNames = who( ...
            '-file', ...
            thisFile);

        if ~any(strcmp( ...
                fileVariableNames, ...
                thisVariable))

            error('Variable "%s" was not found in:\n%s', ...
                thisVariable, ...
                thisFile);
        end

        D_model = load( ...
            thisFile, ...
            thisVariable);

        thisAnnualNRMSE = double( ...
            D_model.(thisVariable));

        clear D_model

        if size(thisAnnualNRMSE, 1) ~= nLatitude || ...
                size(thisAnnualNRMSE, 2) ~= nLongitude

            error([ ...
                '%s in file:\n%s\nhas spatial size [%d, %d], ', ...
                'whereas CommonValid has size [%d, %d].'], ...
                thisVariable, ...
                thisFile, ...
                size(thisAnnualNRMSE, 1), ...
                size(thisAnnualNRMSE, 2), ...
                nLatitude, ...
                nLongitude);
        end

        if ndims(thisAnnualNRMSE) < 3 || ...
                size(thisAnnualNRMSE, 3) < nYear

            error([ ...
                '%s in file:\n%s\nmust contain at least three ', ...
                'annual NRMSE layers. Actual size: %s.'], ...
                thisVariable, ...
                thisFile, ...
                mat2str(size(thisAnnualNRMSE)));
        end

        for iYear = 1:nYear

            annualNRMSEAll( ...
                :, :, iModel, iYear, iRun) = ...
                thisAnnualNRMSE(:, :, iYear);
        end

        fprintf('%-7s : %s loaded, size = %s\n', ...
            modelLabels{iModel}, ...
            thisVariable, ...
            mat2str(size(thisAnnualNRMSE)));

        clear thisAnnualNRMSE fileVariableNames
    end
end

%% ===================== Construct strict common mask =====================

strictCommonMask = baseValidMask;

for iRun = 1:nRun

    for iYear = 1:nYear

        for iModel = 1:nModel

            thisMap = annualNRMSEAll( ...
                :, :, iModel, iYear, iRun);

            strictCommonMask = ...
                strictCommonMask & ...
                isfinite(thisMap);
        end
    end
end

fprintf('\nStrict common pixels across all runs, years, and models: %d\n', ...
    nnz(strictCommonMask));

if nnz(strictCommonMask) == 0

    error([ ...
        'No pixels remain under the strict common-mask requirement.']);
end

%% ===================== Screening-range loop =====================

nRange = numel(rangeLabels);

rangeResults = cell(nRange, 1);
rangeWeightedTables = cell(nRange, 1);
rangeRegionTables = cell(nRange, 1);

for iRange = 1:nRange

    thisLower = ...
        lowerARThreshold(iRange);

    thisUpper = ...
        upperARThreshold(iRange);

    thisTag = ...
        rangeTags{iRange};

    fprintf('\n');
    fprintf('================================================================================\n');
    fprintf('SCREENING RANGE %d OF %d: AR NRMSE IN [%.2f, %.2f)\n', ...
        iRange, ...
        nRange, ...
        thisLower, ...
        thisUpper);
    fprintf('================================================================================\n');

    caseOutDir = fullfile( ...
        outDir, ...
        thisTag);

    if ~exist(caseOutDir, 'dir')
        mkdir(caseOutDir);
    end

    nineTableExcelFile = fullfile( ...
        outDir, ...
        ['s4_model_selection_9_case_tables_', ...
        thisTag, ...
        '.xlsx']);

    weightedExcelFile = fullfile( ...
        outDir, ...
        ['s4_model_selection_weighted_table_', ...
        thisTag, ...
        '.xlsx']);

    if isfile(nineTableExcelFile)
        delete(nineTableExcelFile);
    end

    if isfile(weightedExcelFile)
        delete(weightedExcelFile);
    end

    %% ---------- Initialize case containers ----------

    caseTables = cell(nRun, nYear);
    caseResults = cell(nRun, nYear);

    caseRunColumn = strings(nCase, 1);
    caseYearColumn = nan(nCase, 1);

    caseValidPixelCount = nan(nCase, 1);
    caseComputePixelCount = nan(nCase, 1);
    caseComputePixelPct = nan(nCase, 1);

    caseNoGainCount = nan(nCase, 1);
    caseNoGainPct = nan(nCase, 1);

    caseLowARCount = nan(nCase, 1);
    caseLowARPct = nan(nCase, 1);

    caseHighARCount = nan(nCase, 1);
    caseHighARPct = nan(nCase, 1);

    caseNotComputeCount = nan(nCase, 1);
    caseNotComputePct = nan(nCase, 1);

    % Pooled positive-gain samples used for the weighted table.
    pooledGainValues = cell(nTargetModel, 1);
    pooledGapValues = cell(nTargetModel, 1);

    for iTarget = 1:nTargetModel

        pooledGainValues{iTarget} = zeros(0, 1);
        pooledGapValues{iTarget} = zeros(0, 1);
    end

    caseIndex = 0;

    %% ---------- Calculate nine case tables ----------

    for iRun = 1:nRun

        for iYear = 1:nYear

            caseIndex = caseIndex + 1;

            thisRunName = runNames{iRun};
            thisTestYear = testYears(iYear);

            fprintf('\n');
            fprintf('--------------------------------------------------------------------------------\n');
            fprintf('CASE %d OF %d: %s RUN, %d TEST YEAR\n', ...
                caseIndex, ...
                nCase, ...
                upper(thisRunName), ...
                thisTestYear);
            fprintf('--------------------------------------------------------------------------------\n');

            thisNRMSEStack = squeeze( ...
                annualNRMSEAll(:, :, :, iYear, iRun));

            if useStrictCommonMaskAcrossAllCases

                thisBaseMask = strictCommonMask;

            else

                thisBaseMask = ...
                    baseValidMask & ...
                    all(isfinite(thisNRMSEStack), 3);
            end

            [thisTable, thisResult, ...
                thisGainValueCells, thisGapValueCells] = ...
                calculateScreeningCase( ...
                thisNRMSEStack, ...
                thisBaseMask, ...
                modelLabels, ...
                targetModelIndices, ...
                thisLower, ...
                thisUpper, ...
                tolerance);

            caseTables{iRun, iYear} = ...
                thisTable;

            caseResults{iRun, iYear} = ...
                thisResult;

            %% ------ Append pooled samples ------

            for iTarget = 1:nTargetModel

                pooledGainValues{iTarget} = [ ...
                    pooledGainValues{iTarget}; ...
                    thisGainValueCells{iTarget}(:)]; %#ok<AGROW>

                pooledGapValues{iTarget} = [ ...
                    pooledGapValues{iTarget}; ...
                    thisGapValueCells{iTarget}(:)]; %#ok<AGROW>
            end

            %% ------ Store region summary ------

            caseRunColumn(caseIndex) = ...
                string(thisRunName);

            caseYearColumn(caseIndex) = ...
                thisTestYear;

            caseValidPixelCount(caseIndex) = ...
                thisResult.nValid;

            caseComputePixelCount(caseIndex) = ...
                thisResult.nCompute;

            caseComputePixelPct(caseIndex) = ...
                safePercentage( ...
                thisResult.nCompute, ...
                thisResult.nValid);

            caseNoGainCount(caseIndex) = ...
                thisResult.nNotComputeNoGain;

            caseNoGainPct(caseIndex) = ...
                safePercentage( ...
                thisResult.nNotComputeNoGain, ...
                thisResult.nValid);

            caseLowARCount(caseIndex) = ...
                thisResult.nNotComputeLowAR;

            caseLowARPct(caseIndex) = ...
                safePercentage( ...
                thisResult.nNotComputeLowAR, ...
                thisResult.nValid);

            caseHighARCount(caseIndex) = ...
                thisResult.nNotComputeHighAR;

            caseHighARPct(caseIndex) = ...
                safePercentage( ...
                thisResult.nNotComputeHighAR, ...
                thisResult.nValid);

            caseNotComputeCount(caseIndex) = ...
                thisResult.nNotCompute;

            caseNotComputePct(caseIndex) = ...
                safePercentage( ...
                thisResult.nNotCompute, ...
                thisResult.nValid);

            %% ------ Display case table ------

            fprintf('\nRegion counts:\n');

            fprintf('  Valid pixels             : %6d\n', ...
                thisResult.nValid);

            fprintf('  Computation pixels       : %6d | %6.2f%% of valid\n', ...
                thisResult.nCompute, ...
                safePercentage( ...
                thisResult.nCompute, ...
                thisResult.nValid));

            fprintf('  No-gain pixels           : %6d | %6.2f%% of valid\n', ...
                thisResult.nNotComputeNoGain, ...
                safePercentage( ...
                thisResult.nNotComputeNoGain, ...
                thisResult.nValid));

            fprintf('  AR NRMSE < %.2f          : %6d | %6.2f%% of valid\n', ...
                thisLower, ...
                thisResult.nNotComputeLowAR, ...
                safePercentage( ...
                thisResult.nNotComputeLowAR, ...
                thisResult.nValid));

            fprintf('  AR NRMSE >= %.2f         : %6d | %6.2f%% of valid\n', ...
                thisUpper, ...
                thisResult.nNotComputeHighAR, ...
                safePercentage( ...
                thisResult.nNotComputeHighAR, ...
                thisResult.nValid));

            fprintf('\nModel statistics within the screening range:\n\n');

            disp(thisTable);

            %% ------ Save individual CSV ------

            csvFile = fullfile( ...
                caseOutDir, ...
                sprintf( ...
                'Table_%02d_%s_%d.csv', ...
                caseIndex, ...
                thisRunName, ...
                thisTestYear));

            writetable( ...
                thisTable, ...
                csvFile, ...
                'WriteRowNames', ...
                true);

            %% ------ Save table as Excel sheet ------

            sheetName = sprintf( ...
                '%s_%d', ...
                thisRunName, ...
                thisTestYear);

            writetable( ...
                thisTable, ...
                nineTableExcelFile, ...
                'Sheet', ...
                sheetName, ...
                'WriteRowNames', ...
                true);
        end
    end

    %% ---------- Region screening summary ----------

    regionSummaryTable = table( ...
        caseRunColumn, ...
        caseYearColumn, ...
        caseValidPixelCount, ...
        caseComputePixelCount, ...
        round(caseComputePixelPct, 2), ...
        caseNotComputeCount, ...
        round(caseNotComputePct, 2), ...
        caseNoGainCount, ...
        round(caseNoGainPct, 2), ...
        caseLowARCount, ...
        round(caseLowARPct, 2), ...
        caseHighARCount, ...
        round(caseHighARPct, 2), ...
        'VariableNames', { ...
        'Run', ...
        'TestYear', ...
        'ValidPixels', ...
        'ComputationPixels', ...
        'ComputationPixelsPct', ...
        'NonComputationPixels', ...
        'NonComputationPixelsPct', ...
        'NoGainPixels', ...
        'NoGainPixelsPct', ...
        'LowARPixels', ...
        'LowARPixelsPct', ...
        'HighARPixels', ...
        'HighARPixelsPct'});

    regionSummaryCsvFile = fullfile( ...
        outDir, ...
        ['Region_Screening_Summary_', ...
        thisTag, ...
        '.csv']);

    writetable( ...
        regionSummaryTable, ...
        regionSummaryCsvFile);

    %% ---------- Weighted nine-case aggregation ----------

    totalComputationPixelEvaluations = sum( ...
        caseComputePixelCount, ...
        'omitnan');

    aggregateGainCount = zeros(nTargetModel, 1);
    aggregateGainPct = nan(nTargetModel, 1);

    aggregateMeanGainVsAR = nan(nTargetModel, 1);
    aggregateMedianGainVsAR = nan(nTargetModel, 1);

    aggregateMeanGapToBest = nan(nTargetModel, 1);
    aggregateMedianGapToBest = nan(nTargetModel, 1);

    for iTarget = 1:nTargetModel

        allGainValues = ...
            pooledGainValues{iTarget};

        allGapValues = ...
            pooledGapValues{iTarget};

        validGainValues = ...
            allGainValues(isfinite(allGainValues));

        validGapValues = ...
            allGapValues(isfinite(allGapValues));

        aggregateGainCount(iTarget) = ...
            numel(validGainValues);

        aggregateGainPct(iTarget) = ...
            safePercentage( ...
            aggregateGainCount(iTarget), ...
            totalComputationPixelEvaluations);

        if ~isempty(validGainValues)

            aggregateMeanGainVsAR(iTarget) = mean( ...
                validGainValues, ...
                'omitnan');

            aggregateMedianGainVsAR(iTarget) = median( ...
                validGainValues, ...
                'omitnan');
        end

        if ~isempty(validGapValues)

            aggregateMeanGapToBest(iTarget) = mean( ...
                validGapValues, ...
                'omitnan');

            aggregateMedianGapToBest(iTarget) = median( ...
                validGapValues, ...
                'omitnan');
        end
    end

    %% ---------- Construct weighted screening table ----------

    weightedTable = table( ...
        aggregateGainCount, ...
        round(aggregateGainPct, 1), ...
        round(aggregateMeanGainVsAR, 4), ...
        round(aggregateMedianGainVsAR, 4), ...
        round(aggregateMeanGapToBest, 4), ...
        round(aggregateMedianGapToBest, 4), ...
        'RowNames', ...
        targetModelNames, ...
        'VariableNames', { ...
        'GainPixels', ...
        'GainPixelsPct', ...
        'MeanRedVsAR', ...
        'MedianRedVsAR', ...
        'MeanGapToBest', ...
        'MedianGapToBest'});

    %% ---------- Display weighted table ----------

    fprintf('\n');
    fprintf('================================================================================\n');
    fprintf('        WEIGHTED SUMMARY ACROSS NINE RUN-YEAR TABLES\n');
    fprintf('================================================================================\n');

    fprintf('Screening range: AR NRMSE in [%.2f, %.2f), ', ...
        thisLower, ...
        thisUpper);

    fprintf('excluding no-gain pixels.\n');

    fprintf('Number of cases                         : %d\n', ...
        nCase);

    fprintf('Total computation pixel-evaluations     : %d\n', ...
        totalComputationPixelEvaluations);

    fprintf('\nAggregation rules:\n');

    fprintf([ ...
        '  GainPixels is the total number of positive-gain ', ...
        'pixel-evaluations.\n']);

    fprintf([ ...
        '  GainPixelsPct is weighted by each case''s computation-', ...
        'region pixel count.\n']);

    fprintf([ ...
        '  Mean reductions and gaps are weighted by positive-gain ', ...
        'pixel counts.\n']);

    fprintf([ ...
        '  Median reductions and gaps are recalculated from pooled ', ...
        'positive-gain samples.\n\n']);

    disp(weightedTable);

    fprintf('================================================================================\n');

    %% ---------- Save weighted table ----------

    writetable( ...
        weightedTable, ...
        weightedExcelFile, ...
        'Sheet', ...
        'Weighted_Screening', ...
        'WriteRowNames', ...
        true);

    weightedCsvFile = fullfile( ...
        outDir, ...
        ['s4_model_selection_weighted_table_', ...
        thisTag, ...
        '.csv']);

    writetable( ...
        weightedTable, ...
        weightedCsvFile, ...
        'WriteRowNames', ...
        true);

    %% ---------- Store range results ----------

    rangeResults{iRange} = struct( ...
        'lowerARThreshold', thisLower, ...
        'upperARThreshold', thisUpper, ...
        'caseTables', {caseTables}, ...
        'caseResults', {caseResults}, ...
        'regionSummaryTable', regionSummaryTable, ...
        'pooledGainValues', {pooledGainValues}, ...
        'pooledGapValues', {pooledGapValues}, ...
        'totalComputationPixelEvaluations', ...
        totalComputationPixelEvaluations, ...
        'weightedTable', weightedTable);

    rangeWeightedTables{iRange} = weightedTable;
    rangeRegionTables{iRange} = regionSummaryTable;
end

%% ===================== Save MAT results =====================

resultMatFile = fullfile( ...
    outDir, ...
    's4_model_selection_results.mat');

save( ...
    resultMatFile, ...
    'modelLabels', ...
    'targetModelNames', ...
    'annualNRMSEVarNames', ...
    'runNames', ...
    'testYears', ...
    'resultFileGroups', ...
    'rangeLabels', ...
    'rangeTags', ...
    'lowerARThreshold', ...
    'upperARThreshold', ...
    'tolerance', ...
    'useStrictCommonMaskAcrossAllCases', ...
    'baseValidMask', ...
    'strictCommonMask', ...
    'annualNRMSEAll', ...
    'rangeResults', ...
    'rangeWeightedTables', ...
    'rangeRegionTables', ...
    '-v7.3');

%% ===================== Completion message =====================

fprintf('\nCompleted: annual model-selection screening analysis.\n');

fprintf('Screening ranges evaluated: %d\n', ...
    nRange);

fprintf('Output directory:\n%s\n', ...
    outDir);

%% ========================================================================
%% Local function: calculate one run-year screening table
%% ========================================================================

function [T_model, R, gainValueCells, gapValueCells] = ...
    calculateScreeningCase( ...
    NRMSEStack, ...
    inputValidMask, ...
    modelLabels, ...
    targetModelIndices, ...
    lowerThreshold, ...
    upperThreshold, ...
    tolerance)

    nModel = size(NRMSEStack, 3);

    if nModel ~= numel(modelLabels)

        error([ ...
            'The number of model layers does not match modelLabels.']);
    end

    validMask = ...
        logical(inputValidMask) & ...
        all(isfinite(NRMSEStack), 3);

    if nnz(validMask) == 0

        error('No valid pixels remain in the current run-year case.');
    end

    % Remove invalid values from all model maps.
    for iModel = 1:nModel

        thisMap = NRMSEStack(:, :, iModel);

        thisMap(~validMask) = NaN;

        NRMSEStack(:, :, iModel) = ...
            thisMap;
    end

    AR = NRMSEStack(:, :, 1);

    %% ---------- Annual all-model fusion ----------

    [allFusionNRMSE, bestModelIndex] = min( ...
        NRMSEStack, ...
        [], ...
        3);

    allFusionNRMSE(~validMask) = NaN;
    bestModelIndex(~validMask) = NaN;

    %% ---------- Screening masks ----------

    noGainMask = ...
        validMask & ...
        (AR - allFusionNRMSE <= tolerance);

    lowARMask = ...
        validMask & ...
        AR < lowerThreshold;

    highARMask = ...
        validMask & ...
        AR >= upperThreshold;

    computeMask = ...
        validMask & ...
        ~noGainMask & ...
        AR >= lowerThreshold & ...
        AR < upperThreshold;

    notComputeMask = ...
        validMask & ...
        ~computeMask;

    % Mutually exclusive non-computation categories.
    %
    % Priority:
    %   1. No gain
    %   2. Low AR among remaining pixels
    %   3. High AR among remaining pixels

    notComputeNoGain = ...
        validMask & ...
        noGainMask;

    notComputeLowAR = ...
        validMask & ...
        ~noGainMask & ...
        AR < lowerThreshold;

    notComputeHighAR = ...
        validMask & ...
        ~noGainMask & ...
        AR >= upperThreshold;

    nValid = nnz(validMask);
    nCompute = nnz(computeMask);
    nNotCompute = nnz(notComputeMask);

    %% ---------- Model statistics ----------

    nTarget = numel(targetModelIndices);

    gainCount = zeros(nTarget, 1);
    gainPct = nan(nTarget, 1);

    meanGainVsAR = nan(nTarget, 1);
    medianGainVsAR = nan(nTarget, 1);

    meanGapToBest = nan(nTarget, 1);
    medianGapToBest = nan(nTarget, 1);

    gainValueCells = cell(nTarget, 1);
    gapValueCells = cell(nTarget, 1);

    for iTarget = 1:nTarget

        modelIndex = ...
            targetModelIndices(iTarget);

        modelNRMSE = ...
            NRMSEStack(:, :, modelIndex);

        %% ------ Positive reduction relative to AR ------

        gainVsAR = ...
            AR - modelNRMSE;

        positiveGainMask = ...
            computeMask & ...
            gainVsAR > tolerance;

        gainValues = ...
            gainVsAR(positiveGainMask);

        gainValues = ...
            gainValues(isfinite(gainValues));

        gainCount(iTarget) = ...
            numel(gainValues);

        gainPct(iTarget) = ...
            safePercentage( ...
            gainCount(iTarget), ...
            nCompute);

        if gainCount(iTarget) > 0

            meanGainVsAR(iTarget) = mean( ...
                gainValues, ...
                'omitnan');

            medianGainVsAR(iTarget) = median( ...
                gainValues, ...
                'omitnan');
        end

        %% ------ Gap relative to annual all-model fusion best ------

        gapToBest = ...
            modelNRMSE - allFusionNRMSE;

        gapValues = ...
            gapToBest(positiveGainMask);

        gapValues = ...
            gapValues(isfinite(gapValues));

        % Remove tiny negative values caused by numerical precision.
        gapValues( ...
            gapValues < 0 & ...
            gapValues > -tolerance) = 0;

        if any(gapValues < -tolerance)

            warning([ ...
                'Negative gap values below numerical tolerance were ', ...
                'detected for model %s.'], ...
                modelLabels{modelIndex});
        end

        if ~isempty(gapValues)

            meanGapToBest(iTarget) = mean( ...
                gapValues, ...
                'omitnan');

            medianGapToBest(iTarget) = median( ...
                gapValues, ...
                'omitnan');
        end

        gainValueCells{iTarget} = ...
            gainValues(:);

        gapValueCells{iTarget} = ...
            gapValues(:);
    end

    %% ---------- Screening table output ----------

    outputModelNames = ...
        modelLabels(targetModelIndices);

    T_model = table( ...
        gainCount, ...
        round(gainPct, 1), ...
        round(meanGainVsAR, 4), ...
        round(medianGainVsAR, 4), ...
        round(meanGapToBest, 4), ...
        round(medianGapToBest, 4), ...
        'RowNames', ...
        outputModelNames, ...
        'VariableNames', { ...
        'GainPixels', ...
        'GainPixelsPct', ...
        'MeanRedVsAR', ...
        'MedianRedVsAR', ...
        'MeanGapToBest', ...
        'MedianGapToBest'});

    %% ---------- Store detailed case result ----------

    R.validMask = validMask;
    R.AR = AR;

    R.allFusionNRMSE = ...
        allFusionNRMSE;

    R.bestModelIndex = ...
        bestModelIndex;

    R.noGainMask = ...
        noGainMask;

    R.lowARMask = ...
        lowARMask;

    R.highARMask = ...
        highARMask;

    R.computeMask = ...
        computeMask;

    R.notComputeMask = ...
        notComputeMask;

    R.notComputeNoGain = ...
        notComputeNoGain;

    R.notComputeLowAR = ...
        notComputeLowAR;

    R.notComputeHighAR = ...
        notComputeHighAR;

    R.nValid = ...
        nValid;

    R.nCompute = ...
        nCompute;

    R.nNotCompute = ...
        nNotCompute;

    R.nNotComputeNoGain = ...
        nnz(notComputeNoGain);

    R.nNotComputeLowAR = ...
        nnz(notComputeLowAR);

    R.nNotComputeHighAR = ...
        nnz(notComputeHighAR);

    R.gainCount = ...
        gainCount;

    R.gainPct = ...
        gainPct;

    R.meanGainVsAR = ...
        meanGainVsAR;

    R.medianGainVsAR = ...
        medianGainVsAR;

    R.meanGapToBest = ...
        meanGapToBest;

    R.medianGapToBest = ...
        medianGapToBest;

    R.table = ...
        T_model;
end

%% ========================================================================
%% Local function: safe percentage
%% ========================================================================

function percentage = safePercentage( ...
    numerator, ...
    denominator)

    if isempty(denominator) || ...
            ~isfinite(denominator) || ...
            denominator <= 0

        percentage = NaN;

    else

        percentage = ...
            double(numerator) ./ ...
            double(denominator) .* 100;
    end
end
