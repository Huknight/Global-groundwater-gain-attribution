%% ===================== Local functions =====================

function R = calculateAnnualAttribution( ...
    modelNRMSEStack, ...
    modelTDAStack, ...
    analysisMask, ...
    detailedClassNames, ...
    testYear)

    nModel = size(modelNRMSEStack, 3);

    %% ---------- All-model winner ----------

    [allFusion, bestAll9Idx] = min( ...
        modelNRMSEStack, ...
        [], ...
        3);

    allFusion(~analysisMask) = NaN;
    bestAll9Idx(~analysisMask) = NaN;

    %% ---------- Winner-selected TDA ----------

    winnerTDA = nan(size(analysisMask));

    for iModel = 1:nModel

        thisTDAMap = modelTDAStack(:, :, iModel);

        thisWinnerMask = ...
            analysisMask & ...
            bestAll9Idx == iModel;

        winnerTDA(thisWinnerMask) = ...
            thisTDAMap(thisWinnerMask);
    end

    %% ---------- Group-level stacks ----------

    linearStack = modelNRMSEStack(:, :, 1:3);
    nonlinearStack = modelNRMSEStack(:, :, 4:6);
    nonlinearXStack = modelNRMSEStack(:, :, 7:9);

    [linearFusion, bestLinearLocalIdx] = min( ...
        linearStack, ...
        [], ...
        3);

    [nonlinearFusion, bestNonlinearLocalIdx] = min( ...
        nonlinearStack, ...
        [], ...
        3);

    [nonlinearXFusion, bestNonlinearXLocalIdx] = min( ...
        nonlinearXStack, ...
        [], ...
        3);

    linearFusion(~analysisMask) = NaN;
    nonlinearFusion(~analysisMask) = NaN;
    nonlinearXFusion(~analysisMask) = NaN;

    bestLinearLocalIdx(~analysisMask) = NaN;
    bestNonlinearLocalIdx(~analysisMask) = NaN;
    bestNonlinearXLocalIdx(~analysisMask) = NaN;

    %% ---------- Rank the three groups ----------

    groupFusionStack = cat( ...
        3, ...
        linearFusion, ...
        nonlinearFusion, ...
        nonlinearXFusion);

    [sortedGroupNRMSE, sortedGroupIdx] = sort( ...
        groupFusionStack, ...
        3, ...
        'ascend');

    bestGroupIdx = sortedGroupIdx(:, :, 1);
    secondGroupIdx = sortedGroupIdx(:, :, 2);

    bestGroupNRMSE = sortedGroupNRMSE(:, :, 1);

    bestGroupIdx(~analysisMask) = NaN;
    secondGroupIdx(~analysisMask) = NaN;
    bestGroupNRMSE(~analysisMask) = NaN;

    %% ---------- Verify group and nine-model winners ----------

    reconstructedWinnerIdx = nan(size(analysisMask));

    maskBestLinear = ...
        analysisMask & ...
        bestGroupIdx == 1;

    maskBestNonlinear = ...
        analysisMask & ...
        bestGroupIdx == 2;

    maskBestNonlinearX = ...
        analysisMask & ...
        bestGroupIdx == 3;

    reconstructedWinnerIdx(maskBestLinear) = ...
        bestLinearLocalIdx(maskBestLinear);

    reconstructedWinnerIdx(maskBestNonlinear) = ...
        bestNonlinearLocalIdx(maskBestNonlinear) + 3;

    reconstructedWinnerIdx(maskBestNonlinearX) = ...
        bestNonlinearXLocalIdx(maskBestNonlinearX) + 6;

    winnerMismatchCount = nnz( ...
        analysisMask & ...
        reconstructedWinnerIdx ~= bestAll9Idx);

    fusionMismatch = abs(bestGroupNRMSE - allFusion);

    maximumFusionMismatch = max( ...
        fusionMismatch(analysisMask), ...
        [], ...
        'omitnan');

    %% ---------- Five gain-category masks ----------

    maskNoGain = ...
        analysisMask & ...
        bestGroupIdx == 1 & ...
        bestLinearLocalIdx == 1;

    maskLinearGain = ...
        analysisMask & ...
        bestGroupIdx == 1 & ...
        (bestLinearLocalIdx == 2 | ...
         bestLinearLocalIdx == 3);

    maskNonlinearGain = ...
        analysisMask & ...
        bestGroupIdx == 2;

    maskHydroClean = ...
        analysisMask & ...
        bestGroupIdx == 3 & ...
        secondGroupIdx == 2 & ...
        bestNonlinearXLocalIdx == ...
        bestNonlinearLocalIdx;

    maskMixedGain = ...
        analysisMask & ...
        bestGroupIdx == 3 & ...
        ~maskHydroClean;

    gainClassMap = nan(size(analysisMask));

    gainClassMap(maskNoGain) = 1;
    gainClassMap(maskLinearGain) = 2;
    gainClassMap(maskNonlinearGain) = 3;
    gainClassMap(maskHydroClean) = 4;
    gainClassMap(maskMixedGain) = 5;

    %% ---------- Detailed Mixed-L and Mixed-N masks ----------

    maskMixedLinearSecond = ...
        analysisMask & ...
        bestGroupIdx == 3 & ...
        secondGroupIdx == 1;

    maskMixedNonlinearSecond = ...
        analysisMask & ...
        bestGroupIdx == 3 & ...
        secondGroupIdx == 2 & ...
        bestNonlinearXLocalIdx ~= ...
        bestNonlinearLocalIdx;

    detailedClassMasks = { ...
        maskNoGain; ...
        maskLinearGain; ...
        maskNonlinearGain; ...
        maskHydroClean; ...
        maskMixedLinearSecond; ...
        maskMixedNonlinearSecond};

    %% ---------- Assignment diagnostics ----------

    classSum = ...
        double(maskNoGain) + ...
        double(maskLinearGain) + ...
        double(maskNonlinearGain) + ...
        double(maskHydroClean) + ...
        double(maskMixedLinearSecond) + ...
        double(maskMixedNonlinearSecond);

    nValid = nnz(analysisMask);

    nAssigned = nnz( ...
        analysisMask & ...
        classSum == 1);

    nUnassigned = nnz( ...
        analysisMask & ...
        classSum == 0);

    nMultiAssigned = nnz( ...
        analysisMask & ...
        classSum > 1);

    %% ---------- Gain decomposition ----------

    AR = modelNRMSEStack(:, :, 1);
    L = linearFusion;
    N = nonlinearFusion;
    X = nonlinearXFusion;
    B = allFusion;

    G_total = AR - B;
    G_total(~analysisMask) = NaN;

    G_linear = nan(size(AR));
    G_nonlinear = nan(size(AR));
    G_hydro = nan(size(AR));
    G_mixed = nan(size(AR));

    G_linear(analysisMask) = 0;
    G_nonlinear(analysisMask) = 0;
    G_hydro(analysisMask) = 0;
    G_mixed(analysisMask) = 0;

    % Linear-gain class
    G_linear(maskLinearGain) = ...
        AR(maskLinearGain) - ...
        B(maskLinearGain);

    % Nonlinear-gain class
    G_linear(maskNonlinearGain) = ...
        AR(maskNonlinearGain) - ...
        L(maskNonlinearGain);

    G_nonlinear(maskNonlinearGain) = ...
        L(maskNonlinearGain) - ...
        N(maskNonlinearGain);

    % Clean hydroclimatic-gain class
    G_linear(maskHydroClean) = ...
        AR(maskHydroClean) - ...
        L(maskHydroClean);

    G_nonlinear(maskHydroClean) = ...
        L(maskHydroClean) - ...
        N(maskHydroClean);

    G_hydro(maskHydroClean) = ...
        N(maskHydroClean) - ...
        X(maskHydroClean);

    % Mixed-L class
    G_linear(maskMixedLinearSecond) = ...
        AR(maskMixedLinearSecond) - ...
        L(maskMixedLinearSecond);

    G_mixed(maskMixedLinearSecond) = ...
        L(maskMixedLinearSecond) - ...
        X(maskMixedLinearSecond);

    % Mixed-N class
    G_linear(maskMixedNonlinearSecond) = ...
        AR(maskMixedNonlinearSecond) - ...
        L(maskMixedNonlinearSecond);

    G_nonlinear(maskMixedNonlinearSecond) = ...
        L(maskMixedNonlinearSecond) - ...
        N(maskMixedNonlinearSecond);

    G_mixed(maskMixedNonlinearSecond) = ...
        N(maskMixedNonlinearSecond) - ...
        X(maskMixedNonlinearSecond);

    %% ---------- Remove tiny numerical noise ----------

    tolerance = 1e-10;

    G_total(abs(G_total) < tolerance) = 0;
    G_linear(abs(G_linear) < tolerance) = 0;
    G_nonlinear(abs(G_nonlinear) < tolerance) = 0;
    G_hydro(abs(G_hydro) < tolerance) = 0;
    G_mixed(abs(G_mixed) < tolerance) = 0;

    %% ---------- Reconstruction check ----------

    G_reconstructed = ...
        G_linear + ...
        G_nonlinear + ...
        G_hydro + ...
        G_mixed;

    reconstructionError = ...
        G_reconstructed - ...
        G_total;

    reconstructionError(~analysisMask) = NaN;

    maxAbsReconstructionError = max( ...
        abs(reconstructionError(analysisMask)), ...
        [], ...
        'omitnan');

    %% ---------- Table 1 calculations ----------

    [Table1, FigureSummaryTable] = createAttributionTables( ...
        detailedClassNames, ...
        detailedClassMasks, ...
        G_total, ...
        G_linear, ...
        G_nonlinear, ...
        G_hydro, ...
        G_mixed, ...
        AR, ...
        analysisMask);

    %% ---------- Store output ----------

    R.testYear = testYear;
    R.analysisMask = analysisMask;
    R.nValid = nValid;

    R.AR_NRMSE = AR;

    R.modelNRMSEStack = modelNRMSEStack;
    R.modelTDAStack = modelTDAStack;

    R.allFusion = allFusion;
    R.bestAll9Idx = bestAll9Idx;
    R.winnerTDA = winnerTDA;

    R.linearFusion = linearFusion;
    R.nonlinearFusion = nonlinearFusion;
    R.nonlinearXFusion = nonlinearXFusion;

    R.bestLinearLocalIdx = bestLinearLocalIdx;
    R.bestNonlinearLocalIdx = bestNonlinearLocalIdx;
    R.bestNonlinearXLocalIdx = bestNonlinearXLocalIdx;

    R.bestGroupIdx = bestGroupIdx;
    R.secondGroupIdx = secondGroupIdx;

    R.maskNoGain = maskNoGain;
    R.maskLinearGain = maskLinearGain;
    R.maskNonlinearGain = maskNonlinearGain;
    R.maskHydroClean = maskHydroClean;
    R.maskMixedGain = maskMixedGain;
    R.maskMixedLinearSecond = maskMixedLinearSecond;
    R.maskMixedNonlinearSecond = ...
        maskMixedNonlinearSecond;

    R.gainClassMap = gainClassMap;

    R.G_total = G_total;
    R.G_linear = G_linear;
    R.G_nonlinear = G_nonlinear;
    R.G_hydro = G_hydro;
    R.G_mixed = G_mixed;

    R.Table1 = Table1;
    R.FigureSummaryTable = FigureSummaryTable;

    R.nAssigned = nAssigned;
    R.nUnassigned = nUnassigned;
    R.nMultiAssigned = nMultiAssigned;

    R.winnerMismatchCount = winnerMismatchCount;
    R.maximumFusionMismatch = maximumFusionMismatch;
    R.maxAbsReconstructionError = ...
        maxAbsReconstructionError;
end

