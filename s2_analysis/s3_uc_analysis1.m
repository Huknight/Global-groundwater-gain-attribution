    classNames, ...
    classMasks, ...
    G_total, ...
    G_linear, ...
    G_nonlinear, ...
    G_hydro, ...
    G_mixed, ...
    AR, ...
    analysisMask)

    nClass = numel(classNames);
    nValid = nnz(analysisMask);

    LinearContributionPct = nan(nClass, 1);
    NonlinearContributionPct = nan(nClass, 1);
    HydroContributionPct = nan(nClass, 1);
    MixedContributionPct = nan(nClass, 1);

    MeanLinearReduction = nan(nClass, 1);
    MeanNonlinearReduction = nan(nClass, 1);
    MeanHydroReduction = nan(nClass, 1);
    MeanMixedReduction = nan(nClass, 1);

    PixelCount = zeros(nClass, 1);
    PixelPct = nan(nClass, 1);
    MeanTotalReduction = nan(nClass, 1);
    MeanTotalReductionPct = nan(nClass, 1);

    for iClass = 1:nClass

        maskClass = classMasks{iClass};

        PixelCount(iClass) = nnz(maskClass);

        PixelPct(iClass) = ...
            PixelCount(iClass) ./ ...
            nValid .* 100;

        if PixelCount(iClass) == 0
            continue;
        end

        totalValues = G_total(maskClass);
        linearValues = G_linear(maskClass);
        nonlinearValues = G_nonlinear(maskClass);
        hydroValues = G_hydro(maskClass);
        mixedValues = G_mixed(maskClass);

        MeanTotalReduction(iClass) = mean( ...
            totalValues, ...
            'omitnan');

        MeanLinearReduction(iClass) = mean( ...
            linearValues, ...
            'omitnan');

        MeanNonlinearReduction(iClass) = mean( ...
            nonlinearValues, ...
            'omitnan');

        MeanHydroReduction(iClass) = mean( ...
            hydroValues, ...
            'omitnan');

        MeanMixedReduction(iClass) = mean( ...
            mixedValues, ...
            'omitnan');

        validRelativeMask = ...
            maskClass & ...
            isfinite(AR) & ...
            AR > 0;

        if nnz(validRelativeMask) > 0

            MeanTotalReductionPct(iClass) = mean( ...
                G_total(validRelativeMask) ./ ...
                AR(validRelativeMask) .* 100, ...
                'omitnan');
        end

        totalReductionSum = sum( ...
            totalValues, ...
            'omitnan');

        if abs(totalReductionSum) > 1e-12

            LinearContributionPct(iClass) = ...
                sum(linearValues, 'omitnan') ./ ...
                totalReductionSum .* 100;

            NonlinearContributionPct(iClass) = ...
                sum(nonlinearValues, 'omitnan') ./ ...
                totalReductionSum .* 100;

            HydroContributionPct(iClass) = ...
                sum(hydroValues, 'omitnan') ./ ...
                totalReductionSum .* 100;

            MixedContributionPct(iClass) = ...
                sum(mixedValues, 'omitnan') ./ ...
                totalReductionSum .* 100;
        end
    end

    Table1 = table( ...
        classNames, ...
        LinearContributionPct, ...
        NonlinearContributionPct, ...
        HydroContributionPct, ...
        MixedContributionPct, ...
        MeanLinearReduction, ...
        MeanNonlinearReduction, ...
        MeanHydroReduction, ...
        MeanMixedReduction, ...
        'VariableNames', { ...
        'AttributionClass', ...
        'LinearContributionPct', ...
        'NonlinearContributionPct', ...
        'HydroContributionPct', ...
        'MixedContributionPct', ...
        'MeanLinearReduction', ...
        'MeanNonlinearReduction', ...
        'MeanHydroReduction', ...
        'MeanMixedReduction'});

    FigureSummaryTable = table( ...
        classNames, ...
        PixelCount, ...
        PixelPct, ...
        MeanTotalReduction, ...
        MeanTotalReductionPct, ...
        'VariableNames', { ...
        'AttributionClass', ...
        'Pixels', ...
        'PixelPct', ...
        'MeanTotalNRMSEReduction', ...
        'MeanTotalReductionPct'});
end

function P = buildAttributionProfile( ...
    R, ...
    positiveClassNames, ...
    positiveClassShortNames)

    ARsafe = double(R.AR_NRMSE);

    ARsafe(~R.analysisMask) = NaN;
    ARsafe(ARsafe <= 0) = NaN;

    GtotalPct = ...
        100 .* R.G_total ./ ARsafe;

    GlinearPct = ...
        100 .* R.G_linear ./ ARsafe;

    GnonlinearPct = ...
        100 .* R.G_nonlinear ./ ARsafe;

    GhydroPct = ...
        100 .* R.G_hydro ./ ARsafe;

    GmixedPct = ...
        100 .* R.G_mixed ./ ARsafe;

    tolerance = 1e-10;

    GtotalPct(abs(GtotalPct) < tolerance) = 0;
    GlinearPct(abs(GlinearPct) < tolerance) = 0;
    GnonlinearPct(abs(GnonlinearPct) < tolerance) = 0;
    GhydroPct(abs(GhydroPct) < tolerance) = 0;
    GmixedPct(abs(GmixedPct) < tolerance) = 0;

    positiveClassMasks = { ...
        R.maskLinearGain; ...
        R.maskNonlinearGain; ...
        R.maskHydroClean; ...
        R.maskMixedLinearSecond; ...
        R.maskMixedNonlinearSecond};

    nPositiveClass = numel(positiveClassMasks);

    orderedIdx = [];

    classCounts = zeros(nPositiveClass, 1);
    classPct = nan(nPositiveClass, 1);

    classMeanTotalReduction = nan(nPositiveClass, 1);
    classMeanTotalReductionPct = nan(nPositiveClass, 1);

    for iClass = 1:nPositiveClass

        maskClass = positiveClassMasks{iClass};

        idxClass = find(maskClass);

        totalGainClass = GtotalPct(idxClass);

        [~, orderClass] = sort( ...
            totalGainClass, ...
            'ascend');

        idxClass = idxClass(orderClass);

        orderedIdx = [ ...
            orderedIdx; ...
            idxClass]; %#ok<AGROW>

        classCounts(iClass) = numel(idxClass);

        if R.nValid > 0

            classPct(iClass) = ...
                classCounts(iClass) ./ ...
                R.nValid .* 100;
        end

        if classCounts(iClass) > 0

            classMeanTotalReduction(iClass) = mean( ...
                R.G_total(maskClass), ...
                'omitnan');

            classMeanTotalReductionPct(iClass) = mean( ...
                GtotalPct(maskClass), ...
                'omitnan');
        end
    end

    nPlot = numel(orderedIdx);

    if nPlot == 0

        error('No positive-gain pixels were found for %d.', ...
            R.testYear);
    end

    Ypct = [ ...
        GlinearPct(orderedIdx), ...
        GnonlinearPct(orderedIdx), ...
        GhydroPct(orderedIdx), ...
        GmixedPct(orderedIdx)];

    Ypct(~isfinite(Ypct)) = 0;

    totalPctOrdered = GtotalPct(orderedIdx);
    totalPctOrdered(~isfinite(totalPctOrdered)) = 0;

    reconstructedPct = sum(Ypct, 2);

    reconstructionErrorPct = ...
        reconstructedPct - ...
        totalPctOrdered;

    maxAbsReconstructionErrorPct = max( ...
        abs(reconstructionErrorPct), ...
        [], ...
        'omitnan');

    classEnds = cumsum(classCounts);

    classStarts = [ ...
        1; ...
        classEnds(1:end-1) + 1];

    classCenters = ...
        (classStarts + classEnds) ./ 2;

    nonEmptyClassMask = classCounts > 0;

    labelCenters = ...
        classCenters(nonEmptyClassMask);

    labelShortNames = ...
        positiveClassShortNames(nonEmptyClassMask);

    labelCounts = ...
        classCounts(nonEmptyClassMask);

    labelPct = ...
        classPct(nonEmptyClassMask);

    labelMeanReduction = ...
        classMeanTotalReduction(nonEmptyClassMask);

    labelMeanReductionPct = ...
        classMeanTotalReductionPct(nonEmptyClassMask);

    separatorX = ...
        classEnds(1:end-1) + 0.5;

    separatorX = unique(separatorX);

    separatorX = separatorX( ...
        separatorX > 1 & ...
        separatorX < nPlot);

    percentile90X = nan(nPositiveClass, 1);
    percentile95X = nan(nPositiveClass, 1);

    for iClass = 1:nPositiveClass

        nClassPixel = classCounts(iClass);

        if nClassPixel <= 0
            continue;
        end

        localPosition90 = max( ...
            1, ...
            ceil(0.90 .* nClassPixel));

        localPosition95 = max( ...
            1, ...
            ceil(0.95 .* nClassPixel));

        percentile90X(iClass) = ...
            classStarts(iClass) + ...
            localPosition90 - 1;

        percentile95X(iClass) = ...
            classStarts(iClass) + ...
            localPosition95 - 1;
    end

    yMaxData = max( ...
        reconstructedPct, ...
        [], ...
        'omitnan');

    P.testYear = R.testYear;

    P.orderedIdx = orderedIdx;
    P.nPlot = nPlot;

    P.Ypct = Ypct;
    P.totalPctOrdered = totalPctOrdered;

    P.classNames = positiveClassNames;
    P.classShortNames = positiveClassShortNames;

    P.classCounts = classCounts;
    P.classPct = classPct;

    P.classStarts = classStarts;
    P.classEnds = classEnds;
    P.classCenters = classCenters;

    P.labelCenters = labelCenters;
    P.labelShortNames = labelShortNames;
    P.labelCounts = labelCounts;
    P.labelPct = labelPct;
    P.labelMeanReduction = labelMeanReduction;
    P.labelMeanReductionPct = labelMeanReductionPct;

    P.separatorX = separatorX;
    P.percentile90X = percentile90X;
    P.percentile95X = percentile95X;

    P.yMaxData = yMaxData;

    P.maxAbsReconstructionErrorPct = ...
        maxAbsReconstructionErrorPct;
end

