    thisGroupMask = stabilityMasks{iGroup};
    thisGroupCount = nnz(thisGroupMask);

    for iYear = 1:nYear

        for iModel = 1:nModel

            thisCount = nnz( ...
                thisGroupMask & ...
                annualResult(iYear).bestAll9Idx == iModel);

            if thisGroupCount > 0

                thisWithinGroupPct = ...
                    thisCount ./ thisGroupCount .* 100;
            else
                thisWithinGroupPct = NaN;
            end

            thisCommonTotalPct = ...
                thisCount ./ nCommonTemporalPixel .* 100;

            winnerCompositionStabilityGroup{end + 1, 1} = ...
                stabilityGroupNames{iGroup}; %#ok<SAGROW>

            winnerCompositionYear(end + 1, 1) = ...
                testYears(iYear); %#ok<SAGROW>

            winnerCompositionModel{end + 1, 1} = ...
                modelNames{iModel}; %#ok<SAGROW>

            winnerCompositionCount(end + 1, 1) = ...
                thisCount; %#ok<SAGROW>

            winnerCompositionWithinGroupPct(end + 1, 1) = ...
                thisWithinGroupPct; %#ok<SAGROW>

            winnerCompositionCommonTotalPct(end + 1, 1) = ...
                thisCommonTotalPct; %#ok<SAGROW>
