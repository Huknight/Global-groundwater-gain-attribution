%% s3_uc_analysis1.m
% Purpose:
%   Evaluate temporal robustness of pixel-wise all-model winners and
%   winner-conditioned gain attribution across the three testing years:
%       1. 2022
%       2. 2023
%       3. 2024
%
% Data source:
%   Only the original model run is used.
%
% Annual result arrays:
%   *_NRMSE(:, :, 1) and *_TDA(:, :, 1): 2022 test year
%   *_NRMSE(:, :, 2) and *_TDA(:, :, 2): 2023 test year
%   *_NRMSE(:, :, 3) and *_TDA(:, :, 3): 2024 test year
%
% Model order:
%   1. AR
%   2. ARIMA
%   3. SARIMA
%   4. SVM
%   5. RF
%   6. LSTM
%   7. SVMX
%   8. RFX
%   9. LSTMX
%
% Five gain categories used for global maps:
%   1. No gain
%   2. Linear gain
%   3. Nonlinear gain
%   4. Hydroclimatic gain
%   5. Mixed gain
%
% Six detailed attribution classes used for profile plots and Table 1:
%   1. No gain
%   2. Linear gain
%   3. Nonlinear gain
%   4. Hydroclimatic gain
%   5. Mixed gain with linear second-best
%   6. Mixed gain with nonlinear second-best
%
% Figures:
%   Fig1-Fig3:
%       Global all-model winner distributions for 2022-2024.
%
%   Fig4-Fig6:
%       Winner-model percentage pie charts for 2022-2024.
%
%   Fig7-Fig9:
%       Global five-class gain-category distributions for 2022-2024.
%
%   Fig10-Fig12:
%       Gain-category percentage pie charts for 2022-2024.
%
%   Fig13:
%       Exact three-year gain-category stability.
%       Blue = unchanged across 2022, 2023, and 2024.
%       Red  = changed in at least one test year.
%
%   Fig14:
%       Gain-category stability percentage pie chart.
%
%   Fig15-Fig17:
%       Pixel-wise hierarchical attribution profiles for 2022-2024.
%
% Tables:
%   1. Annual model-level mean NRMSE and TDA.
%   2. Annual all-model-fusion mean NRMSE and winner-selected TDA.
%   3. Annual winner-model counts and percentages.
%   4. Annual gain-category counts and percentages.
%   5. Exact gain-category stability statistics.
%   6. Winner composition within changed and unchanged pixels.
%   7. Gain-category composition within changed and unchanged pixels.
%   8. Winner-conditioned decomposition tables for 2022-2024.
%
% Important:
%   1. All annual comparisons use one common temporal mask, requiring all
%      nine models to contain finite annual NRMSE values in all three years.
%
%   2. Winner-selected TDA is extracted from the model selected using
%      minimum NRMSE. TDA itself is not used to select the winner.
%
%   3. Strict stability is used:
%      GainCategory_2022 = GainCategory_2023 = GainCategory_2024.
%
%   4. MATLAB min() selects the first model in the defined model order when
%      two models have exactly identical NRMSE values.
%
%   5. Mixed gain is shown as one class in the global category maps, but is
%      divided into Mixed-L and Mixed-N for attribution profiles and Table 1.

